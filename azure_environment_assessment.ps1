function Get-HttpStatusCode {
    <# Best-effort HTTP status of a failed Az call (property first, then message text). #>
    param($ErrorRecord)
    $ex = $ErrorRecord
    if ($ErrorRecord -is [System.Management.Automation.ErrorRecord]) { $ex = $ErrorRecord.Exception }
    $texts = New-List
    $depth = 0
    while ($null -ne $ex -and $depth -lt 6) {
        foreach ($path in @('Response.StatusCode', 'StatusCode', 'HttpStatusCode')) {
            $v = Get-Prop $ex $path
            if ($null -ne $v) {
                $code = $null
                try { $code = [int]$v } catch { try { $code = [int][System.Net.HttpStatusCode][string]$v } catch { $code = $null } }
                if ($code -ge 100 -and $code -le 599) { return $code }
            }
        }
        if ($ex.Message) { $texts.Add([string]$ex.Message) }
        $ex = $ex.InnerException
        $depth++
    }
    $msg = $texts -join ' '
    if ($msg -match '\b401\b|Unauthorized|AuthenticationFailed') { return 401 }
    if ($msg -match '\b403\b|Forbidden|AuthorizationFailed') { return 403 }
    if ($msg -match '\b404\b|NotFound') { return 404 }
    if ($msg -match '\b429\b|TooManyRequests') { return 429 }
    if ($msg -match '\b(5\d\d)\b') { return [int]$Matches[1] }
    if ($msg -match 'InternalServerError') { return 500 }
    if ($msg -match 'BadGateway') { return 502 }
    if ($msg -match 'ServiceUnavailable') { return 503 }
    if ($msg -match 'GatewayTimeout') { return 504 }
    return 0
}

function Invoke-WithRetry {
    <# Runs an Azure call; retries HTTP 429 and 5xx up to $script:MaxRetries (4) retries, i.e. 5
       attempts in total, with exponential backoff. 401/403/404 and everything else are rethrown
       immediately. #>
    [CmdletBinding()]
    param([Parameter(Mandatory = $true)][scriptblock]$ScriptBlock, [string]$Operation = 'Azure call')
    $retryNumber = 0
    while ($true) {
        try {
            return (& $ScriptBlock)
        }
        catch {
            $httpCode = Get-HttpStatusCode -ErrorRecord $_
            $isTransient = ($httpCode -eq 429) -or ($httpCode -ge 500 -and $httpCode -le 599)
            if (-not $isTransient -or $retryNumber -ge $script:MaxRetries) { throw }
            $retryNumber++
            $delay = $script:RetryBaseDelaySeconds * [math]::Pow(2, $retryNumber - 1)
            Write-Step ("    HTTP {0} on {1}; retry {2}/{3} in {4}s" -f $httpCode, $Operation, $retryNumber, $script:MaxRetries, $delay) -Level Warning
            if ($delay -gt 0) { Start-Sleep -Seconds ([int]$delay) }
        }
    }
}

function Initialize-Anonymiser {
    param([switch]$Enabled, [string]$Salt)
    $script:AnonymiseEnabled = [bool]$Enabled
    $script:Hmac = $null
    $script:MaskRegistry = @{}
    $script:MaskRegexCount = -1
    $script:MaskRegex = $null
    if (-not $Enabled) { return }
    if ($Salt) {
        $key = [System.Text.Encoding]::UTF8.GetBytes($Salt)
    }
    else {
        $key = New-Object byte[] 32
        $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
        $rng.GetBytes($key)
        $rng.Dispose()
        Write-Step 'Anonymisation uses a random per-run salt: two runs can only be correlated if the same -AnonymiseSalt is supplied.' -Level Warning
    }
    $script:Hmac = New-Object System.Security.Cryptography.HMACSHA256 (, $key)
}

function Get-Mask {
    <# Returns the value unchanged unless -Anonymise is on; otherwise the first 12 hex characters of
       HMAC-SHA256(salt, value). Names and IDs are lower-cased first (Azure treats them
       case-insensitively); use -CaseSensitive for free text such as tag values. #>
    param([AllowNull()][object]$Value, [switch]$CaseSensitive)
    if (-not $script:AnonymiseEnabled -or $null -eq $script:Hmac) { return $Value }
    if ($null -eq $Value) { return $Value }
    $s = [string]$Value
    if ($s.Length -eq 0) { return $s }
    if (-not $CaseSensitive) { $s = $s.ToLowerInvariant() }
    $hash = $script:Hmac.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($s))
    $sb = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt 6; $i++) { [void]$sb.Append($hash[$i].ToString('x2')) }
    $masked = $sb.ToString()
    # Remember every raw value masked in this run, so error messages and the manifest OutputPath
    # can have exactly those values replaced (Protect-Message).
    if ($null -eq $script:MaskRegistry) { $script:MaskRegistry = @{} }
    if (-not $script:MaskRegistry.ContainsKey($s)) { $script:MaskRegistry[$s] = $masked }
    return $masked
}

function Get-MaskedPrefix {
    <# "10.1.2.0/24" -> "<hash>/24": keeps prefix length so sizing stays usable. #>
    param([string]$Prefix)
    if (-not $script:AnonymiseEnabled -or -not $Prefix) { return $Prefix }
    $len = ''
    if ($Prefix -match '/(\d+)$') { $len = '/' + $Matches[1] }
    return (Get-Mask $Prefix) + $len
}

function Get-MaskedList {
    param([string]$Value, [ValidateSet('Name', 'Prefix', 'CaseSensitive')][string]$Kind = 'Name')
    if (-not $script:AnonymiseEnabled -or -not $Value) { return $Value }
    $out = New-List
    foreach ($item in $Value.Split(';')) {
        if ($item -eq '') { continue }
        switch ($Kind) {
            'Prefix' { $out.Add((Get-MaskedPrefix $item)) }
            'CaseSensitive' { $out.Add((Get-Mask $item -CaseSensitive)) }
            default { $out.Add((Get-Mask $item)) }
        }
    }
    return ($out -join ';')
}

