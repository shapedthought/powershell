function Get-VmSkuInfo {
    param([string]$Region, [string]$VmSize, [string]$SubscriptionId)
    $r = Format-Region $Region
    if (-not $script:State.SkuCache.ContainsKey($r)) {
        $map = @{}
        try {
            $skus = @(Invoke-WithRetry -Operation 'Get-AzComputeResourceSku' -ScriptBlock { Get-AzComputeResourceSku -Location $r -ErrorAction Stop })
            foreach ($s in $skus) {
                if ([string](Get-Prop $s 'ResourceType') -ne 'virtualMachines') { continue }
                $vcpu = $null; $mem = $null
                foreach ($cap in @(Get-Prop $s 'Capabilities')) {
                    if ($cap.Name -eq 'vCPUs') { $vcpu = $cap.Value }
                    elseif ($cap.Name -eq 'MemoryGB') { $mem = $cap.Value }
                }
                $map[([string]$s.Name).ToLowerInvariant()] = @{ vCPUs = $vcpu; MemoryGiB = $mem }
            }
        }
        catch { Add-ErrorRow -SubscriptionId $SubscriptionId -Module 'vm' -Operation "Get-AzComputeResourceSku $r" -Message $_.Exception.Message }
        $script:State.SkuCache[$r] = $map
    }
    if ($VmSize) { return $script:State.SkuCache[$r][$VmSize.ToLowerInvariant()] }
}

function Get-DiskEncryptionLabel {
    param($Disk)
    $labels = New-List
    switch -Regex ([string](Get-Prop $Disk 'Encryption.Type')) {
        'PlatformAndCustomerKeys' { $labels.Add('SSE+CMK') }
        'WithCustomerKey$' { $labels.Add('SSE+CMK') }
        'WithPlatformKey$' { $labels.Add('SSE+PMK') }
    }
    if ((Get-Prop $Disk 'EncryptionSettingsCollection.Enabled') -eq $true) { $labels.Add('ADE') }
    return , $labels
}

function Get-VmInventory {
    param($Subscription)
    $subId = [string]$Subscription.Id
    $records = New-List
    $vms = @(Invoke-WithRetry -Operation 'Get-AzVM' -ScriptBlock { Get-AzVM -ErrorAction Stop })
    $power = @{}
    try {
        foreach ($s in @(Invoke-WithRetry -Operation 'Get-AzVM -Status' -ScriptBlock { Get-AzVM -Status -ErrorAction Stop })) {
            $power[(ConvertTo-Lower $s.Id)] = [string](Get-Prop $s 'PowerState')
        }
    }
    catch { Add-ErrorRow -SubscriptionId $subId -Module 'vm' -Operation 'Get-AzVM -Status' -Message $_.Exception.Message }
    $disks = @()
    try { $disks = @(Invoke-WithRetry -Operation 'Get-AzDisk' -ScriptBlock { Get-AzDisk -ErrorAction Stop }) }
    catch { Add-ErrorRow -SubscriptionId $subId -Module 'vm' -Operation 'Get-AzDisk' -Message $_.Exception.Message }
    $diskById = @{}
    foreach ($d in $disks) { $diskById[(ConvertTo-Lower $d.Id)] = $d }
    $vmNameById = @{}
    foreach ($vm in $vms) { $vmNameById[(ConvertTo-Lower $vm.Id)] = [string]$vm.Name }

    foreach ($vm in $vms) {
        try {
            $rec = New-WorkloadRecord -Output 'vms' -Module 'vm' -ResourceId $vm.Id -Subscription $Subscription -ResourceGroup $vm.ResourceGroupName `
                -Region $vm.Location -Zones (Get-Prop $vm 'Zones') -ResourceName $vm.Name -ResourceType 'Microsoft.Compute/virtualMachines' -Tags (Get-Prop $vm 'Tags') -Candidate $script:WorkloadMap.vm
            $rec.Net.VNetInjected = $true
            $nicRefs = @(Get-Prop $vm 'NetworkProfile.NetworkInterfaces')
            foreach ($n in $nicRefs) {
                $isPrimary = [bool](Get-Prop $n 'Primary')
                if ($nicRefs.Count -eq 1) { $isPrimary = $true }
                $rec.Net.NicRefs.Add(@{ Id = [string]$n.Id; Primary = $isPrimary })
            }
            $primaryRef = $null
            foreach ($r in $rec.Net.NicRefs) { if ($r.Primary) { $primaryRef = $r; break } }
            if ($null -eq $primaryRef -and $rec.Net.NicRefs.Count -gt 0) { $primaryRef = $rec.Net.NicRefs[0] }

            $vmSize = [string](Get-Prop $vm 'HardwareProfile.VmSize')
            $sku = Get-VmSkuInfo -Region $vm.Location -VmSize $vmSize -SubscriptionId $subId
            $diskSkus = New-List; $enc = New-List
            $flags = @{ Ultra = $false; PremV2 = $false; Ephemeral = $false; Unmanaged = $false; Shared = $false }
            $osDiskSize = $null; $osDiskSku = ''; $dataTotal = 0.0; $hyperV = ''; $diskCount = 0

            $os = Get-Prop $vm 'StorageProfile.OsDisk'
            $allDisks = New-List
            if ($os) { $allDisks.Add(@{ Disk = $os; IsOs = $true }) }
            foreach ($dd in @(Get-Prop $vm 'StorageProfile.DataDisks')) { $allDisks.Add(@{ Disk = $dd; IsOs = $false }) }
            foreach ($item in $allDisks) {
                $vd = $item.Disk
                $diskCount++
                $md = $diskById[(ConvertTo-Lower ([string](Get-Prop $vd 'ManagedDisk.Id')))]
                $size = $null; $dsku = ''
                if ($md) {
                    $size = Get-Prop $md 'DiskSizeGB'
                    $dsku = [string](Get-Prop $md 'Sku.Name')
                    if ((Get-Prop $md 'MaxShares') -gt 1) { $flags.Shared = $true }
                    foreach ($l in (Get-DiskEncryptionLabel $md)) { if (-not $enc.Contains($l)) { $enc.Add($l) } }
                    if ($item.IsOs) { $hyperV = [string](Get-Prop $md 'HyperVGeneration') }
                }
                else {
                    $size = Get-Prop $vd 'DiskSizeGB'
                    $dsku = [string](Get-Prop $vd 'ManagedDisk.StorageAccountType')
                }
                if (Get-Prop $vd 'Vhd.Uri') { $flags.Unmanaged = $true; $dsku = 'Unmanaged' }
                if ($item.IsOs -and [string](Get-Prop $vd 'DiffDiskSettings.Option') -eq 'Local') { $flags.Ephemeral = $true; $dsku = 'Ephemeral' }
                if ($dsku -match '^UltraSSD') { $flags.Ultra = $true }
                if ($dsku -match '^PremiumV2') { $flags.PremV2 = $true }
                if ($dsku -and -not $diskSkus.Contains($dsku)) { $diskSkus.Add($dsku) }
                if ($item.IsOs) { $osDiskSize = $size; $osDiskSku = $dsku }
                elseif ($null -ne $size) { $dataTotal += [double]$size }
            }
            if ((Get-Prop $vm 'SecurityProfile.EncryptionAtHost') -eq $true) { $enc.Add('EncryptionAtHost') }
            $securityType = [string](Get-Prop $vm 'SecurityProfile.SecurityType')
            if (-not $securityType) { $securityType = 'Standard' }

            $primaryNic = $null
            if ($primaryRef) { $primaryNic = $script:State.Nics[(ConvertTo-Lower $primaryRef.Id)] }
            $hasPublic = $false
            foreach ($r in $rec.Net.NicRefs) {
                $ni = $script:State.Nics[(ConvertTo-Lower $r.Id)]
                if ($ni -and $ni.PublicIpId) { $hasPublic = $true }
            }

            $c = $rec.Columns
            $c.VmSize = $vmSize
            if ($sku) { $c.vCPUs = $sku.vCPUs; if ($null -ne $sku.MemoryGiB) { $c.Memory_GiB = [math]::Round([double]$sku.MemoryGiB, 2) } }
            $c.OsType = [string](Get-Prop $vm 'StorageProfile.OsDisk.OsType')
            $c.ImagePublisher = [string](Get-Prop $vm 'StorageProfile.ImageReference.Publisher')
            $c.ImageOffer = [string](Get-Prop $vm 'StorageProfile.ImageReference.Offer')
            $c.ImageSku = [string](Get-Prop $vm 'StorageProfile.ImageReference.Sku')
            $c.HyperVGeneration = $hyperV
            $c.SecurityType = $securityType
            $c.PowerState = $power[(ConvertTo-Lower $vm.Id)]
            $c.AvailabilitySet = Get-NameFromId ([string](Get-Prop $vm 'AvailabilitySetReference.Id'))
            $c.ProximityPlacementGroup = Get-NameFromId ([string](Get-Prop $vm 'ProximityPlacementGroup.Id'))
            $c.DiskCount = $diskCount
            $c.OsDiskSku = $osDiskSku
            if ($null -ne $osDiskSize) { $c.OsDiskSize_GiB = [math]::Round([double]$osDiskSize, 2) }
            $c.DataDiskSize_GiB = [math]::Round($dataTotal, 2)
            $osForTotal = 0.0
            if ($null -ne $osDiskSize) { $osForTotal = [double]$osDiskSize }
            $c.TotalProvisioned_GiB = [math]::Round($osForTotal + $dataTotal, 2)
            $c.DiskSkus = $diskSkus -join ';'
            $c.HasUltraDisk = $flags.Ultra
            $c.HasPremiumV2Disk = $flags.PremV2
            $c.HasEphemeralOsDisk = $flags.Ephemeral
            $c.HasUnmanagedDisk = $flags.Unmanaged
            $c.HasSharedDisk = $flags.Shared
            $c.DiskEncryptionTypes = $enc -join ';'
            $c.NicCount = $nicRefs.Count
            if ($primaryNic) { $c.PrivateIpAddress = $primaryNic.PrivateIp }
            $c.HasPublicIp = $hasPublic
            $records.Add($rec)
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'vm' -ResourceKey $vm.Id -Operation 'BuildVmRow' -Message $_.Exception.Message }
    }

    foreach ($d in $disks) {
        try {
            $rec = New-WorkloadRecord -Output 'disks' -Module 'vm' -ResourceId $d.Id -Subscription $Subscription -ResourceGroup $d.ResourceGroupName `
                -Region $d.Location -Zones (Get-Prop $d 'Zones') -ResourceName $d.Name -ResourceType 'Microsoft.Compute/disks' -Tags (Get-Prop $d 'Tags') -Candidate $script:WorkloadMap.vm
            $managedBy = [string](Get-Prop $d 'ManagedBy')
            # Child row: an attached disk inherits the VM's placement; an unattached disk has blank
            # network columns and NetworkAccess N/A.
            if ($managedBy) { $rec.Net.InheritFrom = $managedBy } else { $rec.Net.HasSurface = $false }
            $vmName = ''
            if ($managedBy) {
                $vmName = $vmNameById[(ConvertTo-Lower $managedBy)]
                if (-not $vmName) { $vmName = Get-NameFromId $managedBy }
            }
            $maxShares = Get-Prop $d 'MaxShares'
            $c = $rec.Columns
            $c.ManagedBy = $vmName
            $c.DiskState = [string](Get-Prop $d 'DiskState')
            $c.Sku = [string](Get-Prop $d 'Sku.Name')
            $c.Size_GiB = Get-Prop $d 'DiskSizeGB'
            $c.Tier = [string](Get-Prop $d 'Tier')
            $c.EncryptionType = (Get-DiskEncryptionLabel $d) -join ';'
            $c.DiskAccess = Get-NameFromId ([string](Get-Prop $d 'DiskAccessId'))
            $c.NetworkAccessPolicy = [string](Get-Prop $d 'NetworkAccessPolicy')
            $c.DiskPublicNetworkAccess = [string](Get-Prop $d 'PublicNetworkAccess')
            $c.IsShared = ($null -ne $maxShares -and [int]$maxShares -gt 1)
            $c.MaxShares = $maxShares
            $c.Unattached = (-not $managedBy)
            $c.OsType = [string](Get-Prop $d 'OsType')
            $c.HyperVGeneration = [string](Get-Prop $d 'HyperVGeneration')
            $records.Add($rec)
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'vm' -ResourceKey $d.Id -Operation 'BuildDiskRow' -Message $_.Exception.Message }
    }
    Write-Step ("    {0} VM(s), {1} disk(s)" -f $vms.Count, $disks.Count)
    return , $records
}

function Get-SqlDbInventory {
    param($Subscription)
    $subId = [string]$Subscription.Id
    $records = New-List
    $servers = @(Invoke-WithRetry -Operation 'Get-AzSqlServer' -ScriptBlock { Get-AzSqlServer -ErrorAction Stop })
    foreach ($srv in $servers) {
        $srvId = [string](Get-Prop $srv 'ResourceId', 'Id')
        $rg = [string]$srv.ResourceGroupName
        $sn = [string]$srv.ServerName
        try {
            $fw = @()
            try { $fw = @(Invoke-WithRetry -Operation 'Get-AzSqlServerFirewallRule' -ScriptBlock { Get-AzSqlServerFirewallRule -ResourceGroupName $rg -ServerName $sn -ErrorAction Stop }) }
            catch { Add-ErrorRow -SubscriptionId $subId -Module 'sqldb' -ResourceKey $srvId -Operation 'Get-AzSqlServerFirewallRule' -Message $_.Exception.Message }
            $vnr = @()
            try { $vnr = @(Invoke-WithRetry -Operation 'Get-AzSqlServerVirtualNetworkRule' -ScriptBlock { Get-AzSqlServerVirtualNetworkRule -ResourceGroupName $rg -ServerName $sn -ErrorAction Stop }) }
            catch { Add-ErrorRow -SubscriptionId $subId -Module 'sqldb' -ResourceKey $srvId -Operation 'Get-AzSqlServerVirtualNetworkRule' -Message $_.Exception.Message }
            $entraOnly = $null
            try {
                $ao = Invoke-WithRetry -Operation 'Get-AzSqlServerActiveDirectoryOnlyAuthentication' -ScriptBlock { Get-AzSqlServerActiveDirectoryOnlyAuthentication -ResourceGroupName $rg -ServerName $sn -ErrorAction Stop }
                $entraOnly = [bool](Get-Prop $ao 'AzureADOnlyAuthentication')
            }
            catch { Add-ErrorRow -SubscriptionId $subId -Module 'sqldb' -ResourceKey $srvId -Operation 'Get-AzSqlServerActiveDirectoryOnlyAuthentication' -Message $_.Exception.Message }

            $allowAzure = $false; $openAll = $false; $ipRules = 0
            foreach ($r in $fw) {
                $start = [string](Get-Prop $r 'StartIpAddress'); $end = [string](Get-Prop $r 'EndIpAddress')
                if ($start -eq '0.0.0.0' -and $end -eq '0.0.0.0') { $allowAzure = $true; continue }
                if ($start -eq '0.0.0.0' -and $end -eq '255.255.255.255') { $openAll = $true }
                $ipRules++
            }
            $vnetSubnets = @($vnr | ForEach-Object { [string](Get-Prop $_ 'VirtualNetworkSubnetId') })
            $pna = [string](Get-Prop $srv 'PublicNetworkAccess')
            if (-not $pna) { $pna = 'Enabled' }
            $defaultAction = 'Deny'
            if ($openAll) { $defaultAction = 'Allow' }
            $applyNet = {
                param($r)
                $r.Net.PeTargetId = $srvId
                $r.Net.PeGroupFilter = @('sqlServer')
                $r.Net.PublicNetworkAccess = $pna
                $r.Net.DefaultAction = $defaultAction
                foreach ($s in $vnetSubnets) { if ($s) { $r.Net.VNetRuleSubnetIds.Add($s) } }
                $r.Net.IpRuleCount = $ipRules
            }

            # Hidden parent record (Microsoft.Sql/servers): not exported, but child rows (elastic pools)
            # inherit their placement from it.
            $srvRec = New-WorkloadRecord -Output '' -Module 'sqldb' -ResourceId $srvId -Subscription $Subscription -ResourceGroup $rg `
                -Region (Get-Prop $srv 'Location') -ResourceName $sn -ResourceType 'Microsoft.Sql/servers' -Tags (Get-Prop $srv 'Tags') -Candidate $script:WorkloadMap.sqldb
            & $applyNet $srvRec
            $records.Add($srvRec)
            $dbs = @(Invoke-WithRetry -Operation 'Get-AzSqlDatabase' -ScriptBlock { Get-AzSqlDatabase -ResourceGroupName $rg -ServerName $sn -ErrorAction Stop })
            $poolDbCount = @{}
            foreach ($db in $dbs) {
                $dbName = [string]$db.DatabaseName
                if ($dbName -eq 'master') { continue }
                $pool = [string](Get-Prop $db 'ElasticPoolName')
                if ($pool) { if ($poolDbCount.ContainsKey($pool)) { $poolDbCount[$pool]++ } else { $poolDbCount[$pool] = 1 } }
                $dbId = [string](Get-Prop $db 'ResourceId', 'Id')
                try {
                    $rec = New-WorkloadRecord -Output 'sql_databases' -Module 'sqldb' -ResourceId $dbId -Subscription $Subscription -ResourceGroup $rg `
                        -Region (Get-Prop $db 'Location') -ResourceName "$sn/$dbName" -ResourceType 'Microsoft.Sql/servers/databases' -Tags (Get-Prop $db 'Tags') -Candidate $script:WorkloadMap.sqldb
                    & $applyNet $rec
                    $c = $rec.Columns
                    $c.ServerName = $sn
                    $c.DatabaseName = $dbName
                    $c.Edition = [string](Get-Prop $db 'Edition')
                    $c.SkuName = [string](Get-Prop $db 'SkuName', 'CurrentServiceObjectiveName')
                    if ($pool) { $c.CapacityUnit = 'ElasticPool' }
                    elseif ($c.SkuName -match '^(GP|BC|HS)_' -or $c.Edition -match 'GeneralPurpose|BusinessCritical|Hyperscale') { $c.CapacityUnit = 'vCores' }
                    else { $c.CapacityUnit = 'DTUs' }
                    $c.Capacity = Get-Prop $db 'Capacity'
                    $c.ElasticPoolName = $pool
                    $c.MaxSize_GiB = ConvertTo-GiB (Get-Prop $db 'MaxSizeBytes')
                    $c.BackupStorageRedundancy = [string](Get-Prop $db 'CurrentBackupStorageRedundancy', 'BackupStorageRedundancy', 'RequestedBackupStorageRedundancy')
                    $c.ZoneRedundant = Get-Prop $db 'ZoneRedundant'
                    $c.ReadScale = [string](Get-Prop $db 'ReadScale')
                    $c.ServerPublicNetworkAccess = $pna
                    $c.FirewallRuleCount = $fw.Count
                    $c.AllowAzureServices = $allowAzure
                    $c.EntraOnlyAuth = $entraOnly
                    $c.MinimalTlsVersion = [string](Get-Prop $srv 'MinimalTlsVersion')
                    try {
                        $str = Invoke-WithRetry -Operation 'Get-AzSqlDatabaseBackupShortTermRetentionPolicy' -ScriptBlock { Get-AzSqlDatabaseBackupShortTermRetentionPolicy -ResourceGroupName $rg -ServerName $sn -DatabaseName $dbName -ErrorAction Stop }
                        $c.PitrRetentionDays = Get-Prop $str 'RetentionDays'
                    }
                    catch { Add-ErrorRow -SubscriptionId $subId -Module 'sqldb' -ResourceKey $dbId -Operation 'Get-AzSqlDatabaseBackupShortTermRetentionPolicy' -Message $_.Exception.Message }
                    try {
                        $ltr = Invoke-WithRetry -Operation 'Get-AzSqlDatabaseBackupLongTermRetentionPolicy' -ScriptBlock { Get-AzSqlDatabaseBackupLongTermRetentionPolicy -ResourceGroupName $rg -ServerName $sn -DatabaseName $dbName -ErrorAction Stop }
                        $c.LtrWeeklyRetention = [string](Get-Prop $ltr 'WeeklyRetention')
                        $c.LtrMonthlyRetention = [string](Get-Prop $ltr 'MonthlyRetention')
                        $c.LtrYearlyRetention = [string](Get-Prop $ltr 'YearlyRetention')
                    }
                    catch { Add-ErrorRow -SubscriptionId $subId -Module 'sqldb' -ResourceKey $dbId -Operation 'Get-AzSqlDatabaseBackupLongTermRetentionPolicy' -Message $_.Exception.Message }
                    try {
                        # Management-plane GET; avoids Get-AzSqlDatabaseReplicationLink's partner resource group requirement.
                        $resp = Invoke-WithRetry -Operation 'replicationLinks' -ScriptBlock {
                            $x = Invoke-AzRestMethod -Method GET -Path ($dbId + '/replicationLinks?api-version=2021-11-01') -ErrorAction Stop
                            if ([int]$x.StatusCode -ge 400) { throw ("HTTP {0}: {1}" -f [int]$x.StatusCode, $x.Content) }
                            $x
                        }
                        $roles = New-List
                        $parsed = $resp.Content | ConvertFrom-Json
                        foreach ($l in @(Get-Prop $parsed 'value')) {
                            $role = [string](Get-Prop $l 'properties.role')
                            if ($role -and -not $roles.Contains($role)) { $roles.Add($role) }
                        }
                        if ($roles.Count -eq 0) { $c.GeoReplicationRole = 'None' } else { $c.GeoReplicationRole = $roles -join ';' }
                    }
                    catch { Add-ErrorRow -SubscriptionId $subId -Module 'sqldb' -ResourceKey $dbId -Operation 'Get replicationLinks' -Message $_.Exception.Message }
                    $used = Get-MetricValue -ResourceId $dbId -MetricName 'storage' -Module 'sqldb' -SubscriptionId $subId
                    $c.Used_GiB = ConvertTo-GiB $used
                    $alloc = Get-MetricValue -ResourceId $dbId -MetricName 'allocated_data_storage' -Module 'sqldb' -SubscriptionId $subId
                    $c.Allocated_GiB = ConvertTo-GiB $alloc
                    $records.Add($rec)
                }
