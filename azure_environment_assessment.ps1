function Invoke-AzureEnvironmentAssessment {
    [CmdletBinding()]
    param(
        [ValidateSet('vm', 'sqldb', 'sqlmi', 'cosmos', 'files', 'blob', 'vnet', 'aks', 'avs', 'entra', 'other', 'all')]
        [string[]]$Modules = @('vm', 'sqldb', 'sqlmi', 'cosmos', 'files', 'blob', 'vnet', 'other'),
        [string[]]$SubscriptionId,
        [string]$TenantId,
        [switch]$UseDeviceAuthentication,
        [switch]$UseExistingContext,
        [switch]$BackupAssessment,
        [switch]$SkipMetrics,
        [string[]]$TagNames = @(),
        [switch]$Anonymise,
        [string]$AnonymiseSalt,
        [string]$OutputPath,
        [switch]$AcceptDisclaimer
    )
    $runStart = Get-Date
    $script:ExitCode = 0
    $script:ModuleAvailabilityCache = @{}
    if (-not $OutputPath) { $OutputPath = Join-Path (Get-Location).Path ('AzureAssessment_' + $runStart.ToString('yyyyMMdd_HHmmss')) }
    Initialize-AssessmentState -TagNames $TagNames -SkipMetrics:$SkipMetrics
    $script:AnonymiseEnabled = $false
    $script:Hmac = $null

    # --- Startup check 1: Az.Accounts -----------------------------------------------------------------
    if (-not (Test-ModuleAvailable 'Az.Accounts')) {
        Write-Step 'Az.Accounts is not installed. Install the Az modules first:' -Level Error
        Write-Step '    Install-Module -Name Az -Scope CurrentUser -Repository PSGallery' -Level Error
        $script:ExitCode = 1
        return
    }

    # --- Startup check 2: sub-modules per selected module ----------------------------------------------
    $selected = New-List
    $requested = @($Modules)
    if ($requested -contains 'all') { $requested = $script:AllModuleKeys }
    foreach ($m in $script:AllModuleKeys) { if ($requested -contains $m -or $m -eq 'vnet') { $selected.Add($m) } }
    $enabled = New-List; $disabled = New-List
    foreach ($m in $selected) {
        $missing = @($script:ModuleDependencies[$m] | Where-Object { -not (Test-ModuleAvailable $_) })
        if ($missing.Count -gt 0) {
            $disabled.Add($m)
            $msg = "Module '$m' disabled: missing $($missing -join ', '). Install-Module -Name $($missing -join ',') -Scope CurrentUser"
            Write-Step $msg -Level Warning
            Add-ErrorRow -Module $m -Operation 'ModuleCheck' -Message $msg
        }
        else { $enabled.Add($m) }
    }
    if (-not $SkipMetrics -and -not (Test-ModuleAvailable 'Az.Monitor')) {
        $script:State.SkipMetrics = $true
        $msg = 'Az.Monitor missing: metrics disabled (used-size columns blank). Install-Module -Name Az.Monitor -Scope CurrentUser'
        Write-Step $msg -Level Warning
        Add-ErrorRow -Module 'metrics' -Operation 'ModuleCheck' -Message $msg
    }
    $hasRsv = $false; $hasDpp = $false
    if ($BackupAssessment) {
        $hasRsv = Test-ModuleAvailable 'Az.RecoveryServices'
        $hasDpp = Test-ModuleAvailable 'Az.DataProtection'
        foreach ($pair in @(@('Az.RecoveryServices', $hasRsv), @('Az.DataProtection', $hasDpp))) {
            if (-not $pair[1]) {
                $msg = "Backup assessment for $($pair[0]) disabled: module missing. Install-Module -Name $($pair[0]) -Scope CurrentUser"
                Write-Step $msg -Level Warning
                Add-ErrorRow -Module 'backup' -Operation 'ModuleCheck' -Message $msg
            }
        }
    }

    # --- Startup check 3: consent ------------------------------------------------------------------------
    Write-Host ''
    Write-Step 'DISCLAIMER: this is an UNOFFICIAL community script. It is NOT a Veeam tool and comes with NO support.' -Level Warning
    Write-Step 'It is READ-ONLY: management-plane GET calls only; it creates, changes or tags nothing and reads no data.' -Level Warning
    if (-not $AcceptDisclaimer) {
        $answer = Read-Host 'Type "yes" to continue'
        if ($answer -ne 'yes') { Write-Step 'Consent not given; nothing was collected.' -Level Warning; $script:ExitCode = 2; return }
    }

    Initialize-Anonymiser -Enabled:$Anonymise -Salt $AnonymiseSalt
    if ($Anonymise -and $AnonymiseSalt) { Write-Step 'Anonymisation on with a supplied salt: runs with the same salt can be correlated.' -Level Info }
    # Az/Graph cmdlets write their own warnings, which can embed resource names: silence them while
    # anonymising (this script's own console output only prints masked values or allowlisted text).
    if ($Anonymise) { $WarningPreference = 'SilentlyContinue' }

    $processed = New-List; $skipped = New-List
    $originalContext = $null
    try {
        # --- Connect ------------------------------------------------------------------------------------
        $originalContext = Get-AzContext -ErrorAction SilentlyContinue
        if (-not ($UseExistingContext -and $originalContext -and $originalContext.Account)) {
            $cp = @{ ErrorAction = 'Stop' }
            if ($TenantId) { $cp.TenantId = $TenantId }
            if ($UseDeviceAuthentication) { $cp.UseDeviceAuthentication = $true }
            Write-Step 'Connecting to Azure...'
            Connect-AzAccount @cp | Out-Null
            if (-not $originalContext) { $originalContext = Get-AzContext -ErrorAction SilentlyContinue }
        }
        $ctxTenant = [string](Get-Prop (Get-AzContext -ErrorAction SilentlyContinue) 'Tenant.Id')
        if ($TenantId) { $script:State.TenantId = $TenantId } else { $script:State.TenantId = $ctxTenant }
        try {
            $tn = Get-AzTenant -TenantId $script:State.TenantId -ErrorAction Stop | Select-Object -First 1
            $script:State.TenantDomain = [string](Get-Prop $tn 'DefaultDomain', 'Domains')
            if ($script:State.TenantDomain -match ' ') { $script:State.TenantDomain = $script:State.TenantDomain.Split(' ')[0] }
        }
        catch { Add-ErrorRow -Module 'main' -Operation 'Get-AzTenant' -Message $_.Exception.Message }

        $subArgs = @{ ErrorAction = 'Stop' }
        if ($TenantId) { $subArgs.TenantId = $TenantId }
        $allSubs = @(Invoke-WithRetry -Operation 'Get-AzSubscription' -ScriptBlock { Get-AzSubscription @subArgs })
        $subs = New-List
        $wanted = @{}
        foreach ($s in @($SubscriptionId)) { if ($s) { $wanted[$s.ToLowerInvariant()] = $false } }
        foreach ($s in $allSubs) {
            $sid = ([string]$s.Id).ToLowerInvariant()
            if ($wanted.Count -gt 0) { if (-not $wanted.ContainsKey($sid)) { continue }; $wanted[$sid] = $true }
            if ([string](Get-Prop $s 'State') -ne 'Enabled') {
                $skipped.Add([pscustomobject]@{ SubscriptionId = [string]$s.Id; SubscriptionName = (Get-Mask $s.Name); Reason = 'State ' + [string](Get-Prop $s 'State') })
                continue
            }
            $subs.Add($s)
        }
        foreach ($w in $wanted.Keys) {
            if (-not $wanted[$w]) {
                $skipped.Add([pscustomobject]@{ SubscriptionId = $w; SubscriptionName = ''; Reason = 'Not visible to the signed-in account' })
                Add-ErrorRow -SubscriptionId $w -Module 'main' -Operation 'Get-AzSubscription' -Message 'Requested subscription not visible to the signed-in account.'
            }
        }
        Write-Step ("{0} subscription(s) to assess; modules: {1}" -f $subs.Count, ($enabled -join ', ')) -Level Success

        # --- Pass 1: network backbone, every subscription ------------------------------------------------
        $readable = New-List
        $subRead = @{}    # subscription id -> $true once anything could be read from it
        $subFail = @{}    # subscription id -> reason it was skipped as failing
        $vnetEnabled = $enabled -contains 'vnet'
        Write-Step 'Pass 1/3: network backbone'
        foreach ($s in $subs) {
            $sw = [System.Diagnostics.Stopwatch]::StartNew()
            Write-Step ("  [{0}] {1}" -f $s.Id, (Get-Mask $s.Name))
            # A failing subscription is one where the context cannot be set, or the first call returns
            # 401/403: it is skipped. Any other failure is logged and the subscription carries on.
            try { Invoke-WithRetry -Operation 'Set-AzContext' -ScriptBlock { Set-AzContext -SubscriptionId $s.Id -ErrorAction Stop } | Out-Null }
            catch {
                $subFail[[string]$s.Id] = 'Cannot set context: ' + $_.Exception.Message
                Add-ErrorRow -SubscriptionId $s.Id -Module 'main' -Operation 'Set-AzContext' -Message ('Subscription skipped. ' + $_.Exception.Message)
                Write-Step '    subscription skipped' -Level Warning
                continue
            }
            if ($vnetEnabled) {
                try {
                    Get-NetworkBackbone -Subscription $s
                    $subRead[[string]$s.Id] = $true
                    Write-Step ("    backbone done in {0:n1}s" -f $sw.Elapsed.TotalSeconds) -Level Success
                }
                catch {
                    $code = Get-HttpStatusCode -ErrorRecord $_
                    if ($code -eq 401 -or $code -eq 403) {
                        $subFail[[string]$s.Id] = "HTTP $code on first call: " + $_.Exception.Message
                        Add-ErrorRow -SubscriptionId $s.Id -Module 'vnet' -Operation 'Get-AzVirtualNetwork' -Message ('Subscription skipped. ' + $_.Exception.Message)
                        Write-Step '    subscription skipped' -Level Warning
                        continue
                    }
                    Add-ErrorRow -SubscriptionId $s.Id -Module 'vnet' -Operation 'Get-AzVirtualNetwork' -Message $_.Exception.Message
                    $script:State.PeListingFailed.Add([string]$s.Id)
                }
            }
            else { $script:State.PeListingFailed.Add([string]$s.Id) }
            $readable.Add($s)
        }
        if ($vnetEnabled) {
            foreach ($r in (Get-VNetInventory)) { $script:State.Records.Add($r) }
        }

        # --- Pass 2: workload modules ------------------------------------------------------------------
        Write-Step 'Pass 2/3: workload modules'
        $moduleFunctions = [ordered]@{
            vm = 'Get-VmInventory'; sqldb = 'Get-SqlDbInventory'; sqlmi = 'Get-SqlMiInventory'; cosmos = 'Get-CosmosInventory'
            files = 'Get-FileShareInventory'; blob = 'Get-StorageAccountInventory'; aks = 'Get-AksInventory'; avs = 'Get-AvsInventory'
            other = 'Get-OtherResourceSummary'
        }
        foreach ($s in $readable) {
            $subWatch = [System.Diagnostics.Stopwatch]::StartNew()
            Write-Step ("  [{0}] {1}" -f $s.Id, (Get-Mask $s.Name))
            try { Invoke-WithRetry -Operation 'Set-AzContext' -ScriptBlock { Set-AzContext -SubscriptionId $s.Id -ErrorAction Stop } | Out-Null }
            catch {
                Add-ErrorRow -SubscriptionId $s.Id -Module 'main' -Operation 'Set-AzContext' -Message ('Pass 2 skipped for this subscription. ' + $_.Exception.Message)
                continue
            }
            foreach ($m in $moduleFunctions.Keys) {
                if ($enabled -notcontains $m) { continue }
                $mw = [System.Diagnostics.Stopwatch]::StartNew()
                Write-Step ("    module {0}" -f $m)
                try {
                    $recs = & $moduleFunctions[$m] -Subscription $s
                    foreach ($r in $recs) { $script:State.Records.Add($r) }
                    $subRead[[string]$s.Id] = $true
                    Write-Step ("    module {0} done in {1:n1}s" -f $m, $mw.Elapsed.TotalSeconds) -Level Success
                }
                catch {
                    Add-ErrorRow -SubscriptionId $s.Id -Module $m -Operation $moduleFunctions[$m] -Message $_.Exception.Message
                    Write-Step ("    module {0} skipped for this subscription" -f $m) -Level Warning
                }
            }
            if ($BackupAssessment -and -not ($hasRsv -and $hasDpp)) { Set-CoverageIncomplete $s.Id }
            if ($BackupAssessment -and ($hasRsv -or $hasDpp)) {
                $mw = [System.Diagnostics.Stopwatch]::StartNew()
                try {
                    foreach ($r in (Get-BackupInventory -Subscription $s -RecoveryServices $hasRsv -DataProtection $hasDpp)) { $script:State.Records.Add($r) }
                    $subRead[[string]$s.Id] = $true
                    Write-Step ("    backup assessment done in {0:n1}s" -f $mw.Elapsed.TotalSeconds) -Level Success
                }
                catch { Set-CoverageIncomplete $s.Id; Add-ErrorRow -SubscriptionId $s.Id -Module 'backup' -Operation 'Get-BackupInventory' -Message $_.Exception.Message }
            }
            Write-Step ("  subscription done in {0:n1}s" -f $subWatch.Elapsed.TotalSeconds) -Level Success
        }
        # Manifest: a subscription is listed as skipped only when nothing could be read from it.
        foreach ($s in $subs) {
            $sid = [string]$s.Id
            if ($subRead.ContainsKey($sid)) { $processed.Add([pscustomobject]@{ SubscriptionId = $sid; SubscriptionName = (Get-Mask $s.Name) }) }
            else {
                $reason = 'Nothing could be read from this subscription.'
                if ($subFail.ContainsKey($sid)) { $reason = $subFail[$sid] }
                $skipped.Add([pscustomobject]@{ SubscriptionId = $sid; SubscriptionName = (Get-Mask $s.Name); Reason = $reason })
            }
        }
        if ($enabled -contains 'entra') {
            Write-Step '  tenant: module entra'
            try { foreach ($r in (Get-EntraInventory -TenantId $script:State.TenantId -UseDeviceAuthentication:$UseDeviceAuthentication)) { $script:State.Records.Add($r) } }
            catch { Add-ErrorRow -Module 'entra' -Operation 'Get-EntraInventory' -Message $_.Exception.Message }
        }

        # --- Pass 3: placement --------------------------------------------------------------------------
        Write-Step 'Pass 3/3: placement against the backbone of all subscriptions'
        Resolve-AllPlacement
        if ($BackupAssessment) { Add-BackupCoverage }
    }
    catch {
        # Run-level failure (sign-in, subscription listing, ...): still write diagnostics, but exit non-zero.
        $script:ExitCode = 1
        Add-ErrorRow -Module 'main' -Operation 'Run' -Message $_.Exception.Message
        Write-Step ('Run stopped early: ' + (Protect-Message $_.Exception.Message) + ' -- writing what was collected.') -Level Warning
    }
    finally {
        if ($originalContext) {
            try { Set-AzContext -Context $originalContext -ErrorAction Stop | Out-Null }
            catch { Add-ErrorRow -Module 'main' -Operation 'RestoreContext' -Message $_.Exception.Message }
        }
    }

    # --- Anonymise, summarise, export --------------------------------------------------------------------
    # With -Anonymise, every row (including errors.csv) is masked BEFORE anything is written. If masking
    # fails, no data is written: only a manifest that records the failure, and the exit code is non-zero.
    try { Invoke-OutputMasking }
    catch {
        if ($script:AnonymiseEnabled) {
            $script:ExitCode = 1
            Write-Step 'Anonymisation failed; no data was written.' -Level Error
            try {
                if (-not (Test-Path -Path $OutputPath)) { New-Item -ItemType Directory -Path $OutputPath -Force -ErrorAction Stop | Out-Null }
                $failed = [ordered]@{
                    ScriptVersion = $script:ScriptVersion; StartTimeUtc = $runStart.ToUniversalTime().ToString('o'); EndTimeUtc = (Get-Date).ToUniversalTime().ToString('o')
                    Status = 'Failed: anonymisation error; no data written'; Anonymised = $true
                }
                ConvertTo-Json -InputObject $failed | Set-Content -Path (Join-Path $OutputPath 'manifest.json') -Encoding UTF8 -ErrorAction Stop
            }
            catch { Write-Step 'Could not write the failure manifest either.' -Level Error }
            return
        }
        Add-ErrorRow -Module 'main' -Operation 'Anonymise' -Message $_.Exception.Message
    }
    try { Build-Summaries } catch { Add-ErrorRow -Module 'main' -Operation 'Summaries' -Message $_.Exception.Message }
    $map = $null
    try { $map = Build-EnvironmentMap } catch { Add-ErrorRow -Module 'main' -Operation 'EnvironmentMap' -Message $_.Exception.Message }
    $json = $null
    if ($null -ne $map) {
        $jsonWarnings = $null
        $json = ConvertTo-Json -InputObject $map -Depth 10 -WarningVariable jsonWarnings -WarningAction SilentlyContinue
        if ($jsonWarnings) { Add-ErrorRow -Module 'main' -Operation 'environment_map.json' -Message 'ConvertTo-Json depth 10 exceeded; output truncated.' }
    }
    # Errors are masked last (rows logged during summaries are covered too) and still before any write.
    if ($script:AnonymiseEnabled) {
        try {
            $errs = $script:State.Errors
            for ($i = 0; $i -lt $errs.Count; $i++) { $errs[$i] = ConvertTo-MaskedRow $errs[$i] }
        }
        catch {
            $script:ExitCode = 1
            Write-Step 'Anonymisation of errors.csv failed; no data was written.' -Level Error
            return
        }
    }
    try {
        if (-not (Test-Path -Path $OutputPath)) { New-Item -ItemType Directory -Path $OutputPath -Force -ErrorAction Stop | Out-Null }
        if ($null -ne $json) { $json | Set-Content -Path (Join-Path $OutputPath 'environment_map.json') -Encoding UTF8 -ErrorAction Stop }
        $counts = Export-AssessmentFiles -Path $OutputPath
    }
    catch {
        # A failed write fails the run.
        $script:ExitCode = 1
        Write-Step ('Writing output failed: ' + (Protect-Message $_.Exception.Message)) -Level Error
        return
    }

    $boundParams = [ordered]@{}
    foreach ($k in $PSBoundParameters.Keys) {
        if ($k -eq 'AnonymiseSalt') { continue }
        $v = $PSBoundParameters[$k]
        if ($v -is [System.Management.Automation.SwitchParameter]) { $v = [bool]$v }
        if ($k -eq 'OutputPath') { $v = Protect-OutputPath ([string]$v) }
        $boundParams[$k] = $v
    }
    $boundParams['OutputPath'] = Protect-OutputPath $OutputPath
    $skippedOut = New-List
    foreach ($sk in $skipped) { $skippedOut.Add([pscustomobject]@{ SubscriptionId = $sk.SubscriptionId; SubscriptionName = $sk.SubscriptionName; Reason = (Protect-Message ([string]$sk.Reason)) }) }
    $boundParams['EffectiveModules'] = $enabled.ToArray()
    $manifest = [ordered]@{
        ScriptVersion          = $script:ScriptVersion
        StartTimeUtc           = $runStart.ToUniversalTime().ToString('o')
        EndTimeUtc             = (Get-Date).ToUniversalTime().ToString('o')
        PowerShellVersion      = [string]$PSVersionTable.PSVersion
        PowerShellEdition      = [string]$PSVersionTable.PSEdition
        AzAccountsVersion      = (Get-ModuleVersion 'Az.Accounts')
        AzVersion              = (Get-ModuleVersion 'Az')
        Parameters             = $boundParams
        ModulesDisabled        = $disabled.ToArray()
        SubscriptionsProcessed = $processed.ToArray()
        SubscriptionsSkipped   = $skippedOut.ToArray()
        BackboneComplete       = ($script:State.PeListingFailed.Count -eq 0)
        PrivateEndpointListingFailed = $script:State.PeListingFailed.ToArray()
        ExitCode               = $script:ExitCode
        Anonymised             = [bool]$Anonymise
        ErrorCount             = $script:State.Errors.Count
    }
    try { ConvertTo-Json -InputObject $manifest -Depth 5 | Set-Content -Path (Join-Path $OutputPath 'manifest.json') -Encoding UTF8 -ErrorAction Stop }
    catch { $script:ExitCode = 1; Write-Step ('Writing manifest.json failed: ' + (Protect-Message $_.Exception.Message)) -Level Error; return }

    Write-Host ''
    Write-Step ("Output written to {0}" -f (Protect-OutputPath $OutputPath)) -Level Success
    $counts | Format-Table -AutoSize | Out-String | Write-Host
    $byModule = @{}
    foreach ($e in $script:State.Errors) { $mk = [string]$e.Module; if ($byModule.ContainsKey($mk)) { $byModule[$mk]++ } else { $byModule[$mk] = 1 } }
    if ($byModule.Count -gt 0) {
        Write-Step ("{0} error(s) logged to errors.csv:" -f $script:State.Errors.Count) -Level Warning
        foreach ($mk in ($byModule.Keys | Sort-Object)) { Write-Step ("  {0,-8} {1}" -f $mk, $byModule[$mk]) -Level Warning }
    }
    else { Write-Step 'No errors logged.' -Level Success }
}

