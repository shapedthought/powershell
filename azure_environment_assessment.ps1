function ConvertFrom-ResourceId {
    <# Parses a resource's OWN ID into key/value segments (never fixed offsets). #>
    param([string]$ResourceId)
    $result = @{ SubscriptionId = ''; ResourceGroup = ''; Name = ''; Segments = @{} }
    if (-not $ResourceId) { return $result }
    $parts = $ResourceId.Trim('/').Split('/')
    for ($i = 0; $i -lt $parts.Count - 1; $i += 2) {
        $key = $parts[$i].ToLowerInvariant()
        # 'providers' is followed by the namespace, then type/name pairs: skip both and stay aligned.
        if ($key -eq 'providers') { continue }
        if (-not $result.Segments.ContainsKey($key)) { $result.Segments[$key] = $parts[$i + 1] }
    }
    if ($result.Segments.ContainsKey('subscriptions')) { $result.SubscriptionId = $result.Segments['subscriptions'] }
    if ($result.Segments.ContainsKey('resourcegroups')) { $result.ResourceGroup = $result.Segments['resourcegroups'] }
    $result.Name = $parts[$parts.Count - 1]
    return $result
}

function Get-NameFromId {
    <# Name of the resource the ID belongs to (its own last segment). #>
    param([string]$ResourceId)
    if (-not $ResourceId) { return '' }
    $parts = $ResourceId.Trim('/').Split('/')
    return $parts[$parts.Count - 1]
}

function Get-ResourceTypeFromId {
    param([string]$ResourceId)
    if (-not $ResourceId) { return '' }
    $lower = $ResourceId.ToLowerInvariant()
    $idx = $lower.LastIndexOf('/providers/')
    if ($idx -lt 0) { return '' }
    $parts = $lower.Substring($idx + 11).Split('/')
    $types = New-List
    $types.Add($parts[0])
    for ($i = 1; $i -lt $parts.Count; $i += 2) { $types.Add($parts[$i]) }
    return ($types -join '/')
}

function Get-TagValue {
    param($Tags, [string]$Name)
    if ($null -eq $Tags) { return '' }
    if ($Tags -is [System.Collections.IDictionary]) {
        foreach ($k in $Tags.Keys) { if ([string]$k -eq $Name) { return [string]$Tags[$k] } }
        return ''
    }
    foreach ($p in $Tags.PSObject.Properties) { if ($p.Name -eq $Name) { return [string]$p.Value } }
    return ''
}

function Get-TagPairs {
    param($Tags)
    $pairs = New-List
    if ($null -eq $Tags) { return , $pairs }
    if ($Tags -is [System.Collections.IDictionary]) {
        foreach ($k in $Tags.Keys) { $pairs.Add(@{ Key = [string]$k; Value = [string]$Tags[$k] }) }
    }
    else {
        foreach ($p in $Tags.PSObject.Properties) { $pairs.Add(@{ Key = $p.Name; Value = [string]$p.Value }) }
    }
    return , $pairs
}

function Write-Step {
    param([string]$Message, [ValidateSet('Progress', 'Success', 'Warning', 'Error', 'Info')][string]$Level = 'Progress')
    $color = switch ($Level) { 'Progress' { 'Cyan' } 'Success' { 'Green' } 'Warning' { 'Yellow' } 'Error' { 'Red' } default { 'Gray' } }
    Write-Host $Message -ForegroundColor $color
}

