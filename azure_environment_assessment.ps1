        $m = Get-Module -ListAvailable -Name $Name -ErrorAction SilentlyContinue | Select-Object -First 1
        $script:ModuleAvailabilityCache[$Name] = [bool]$m
    }
    return $script:ModuleAvailabilityCache[$Name]
}

