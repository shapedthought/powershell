function Protect-Message {
    <# When anonymising, raw error text is NOT exported: Azure messages embed resource names, IDs and
       paths that the run may never have seen (and so could not have masked). Instead, return an
       allowlisted diagnostic: the HTTP status code and any recognised Azure error codes, e.g.
       "HTTP 403; AuthorizationFailed". Anything else becomes "details withheld (anonymised)". #>
    param([string]$Message)
    if (-not $script:AnonymiseEnabled -or -not $Message) { return $Message }
    $parts = New-List
    $status = [regex]::Match($Message, '(?<![\d.])([45]\d\d)(?![\d.])')
    if ($status.Success) { $parts.Add('HTTP ' + $status.Groups[1].Value) }
    foreach ($code in $script:AllowedErrorCodes) {
        if ([regex]::IsMatch($Message, '(?<![A-Za-z0-9])' + [regex]::Escape($code) + '(?![A-Za-z0-9])', 'IgnoreCase')) {
            if (-not $parts.Contains($code)) { $parts.Add($code) }
        }
    }
    if ($parts.Count -eq 0) { return 'details withheld (anonymised)' }
    return ($parts -join '; ')
}

function Protect-OutputPath {
    <# The output path can contain user, customer or project names that never pass through the mask
       registry, so when anonymising it is hashed as a whole. #>
    param([string]$Path)
    if (-not $script:AnonymiseEnabled -or -not $Path) { return $Path }
    return (Get-Mask $Path -CaseSensitive)
}

function Add-ErrorRow {
    param([string]$SubscriptionId, [string]$Module, [string]$ResourceKey, [string]$Operation, [string]$Message)
    $msg = ''
    if ($Message) { $msg = ($Message -replace '\s+', ' ').Trim() }
    $row = [pscustomobject][ordered]@{
        Timestamp      = (Get-Date).ToUniversalTime().ToString('o')
        SubscriptionId = $SubscriptionId
        Module         = $Module
        ResourceKey    = (ConvertTo-Lower $ResourceKey)
        Operation      = $Operation
        Message        = $msg
    }
    if ($script:State) { $script:State.Errors.Add($row) }
    $shown = $msg
    if ($script:AnonymiseEnabled) { $shown = Protect-Message $msg }
    if ($shown.Length -gt 160) { $shown = $shown.Substring(0, 160) + '...' }
    Write-Step ("    [{0}] {1}: {2}" -f $Module, $Operation, $shown) -Level Warning
}

function Get-MetricSettings {
    <# Time grain (coarsest supported, <= 1 day) and aggregation (Maximum, else Average) per resource
       type + metric, cached. #>
    param([string]$ResourceId, [string]$MetricName, [string]$Module, [string]$SubscriptionId, [string]$ResourceKey)
    $cacheKey = (Get-ResourceTypeFromId $ResourceId) + '|' + $MetricName.ToLowerInvariant()
    if ($script:State.MetricDefCache.ContainsKey($cacheKey)) { return $script:State.MetricDefCache[$cacheKey] }
    $settings = @{ TimeGrain = [timespan]'01:00:00'; Aggregation = 'Maximum' }
    try {
        $defs = @(Invoke-WithRetry -Operation "Get-AzMetricDefinition $MetricName" -ScriptBlock {
                Get-AzMetricDefinition -ResourceId $ResourceId -MetricName $MetricName -ErrorAction Stop -WarningAction SilentlyContinue
            })
        if ($defs.Count -gt 0) {
            $def = $defs[0]
            $best = $null
            foreach ($a in @(Get-Prop $def 'MetricAvailabilities')) {
                $g = Get-Prop $a 'TimeGrain'
                if ($null -eq $g) { continue }
                $ts = [timespan]$g
                if ($ts -le [timespan]'1.00:00:00' -and ($null -eq $best -or $ts -gt $best)) { $best = $ts }
            }
            if ($null -ne $best) { $settings.TimeGrain = $best }
            $aggs = @(Get-Prop $def 'SupportedAggregationTypes') | ForEach-Object { [string]$_ }
            if ($aggs -contains 'Maximum') { $settings.Aggregation = 'Maximum' }
            elseif ($aggs -contains 'Average') { $settings.Aggregation = 'Average' }
            else {
                $primary = [string](Get-Prop $def 'PrimaryAggregationType')
                if ($primary -eq 'Average') { $settings.Aggregation = 'Average' }
            }
        }
    }
    catch {
        Add-ErrorRow -SubscriptionId $SubscriptionId -Module $Module -ResourceKey $ResourceKey -Operation "Get-AzMetricDefinition $MetricName" -Message ("Using PT1H/Maximum. " + $_.Exception.Message)
    }
    $script:State.MetricDefCache[$cacheKey] = $settings
    return $settings
}

function Get-MetricValue {
    <# Maximum (or Average) of one Azure Monitor metric over the last 24 hours. Returns $null and logs
       an errors.csv row when the metric errors or returns nothing. Never substitutes another value. #>
    param([string]$ResourceId, [string]$MetricName, [string]$Module, [string]$SubscriptionId, [string]$ResourceKey)
    if ($script:State.SkipMetrics) { return $null }
    if (-not $ResourceKey) { $ResourceKey = $ResourceId }
    $settings = Get-MetricSettings -ResourceId $ResourceId -MetricName $MetricName -Module $Module -SubscriptionId $SubscriptionId -ResourceKey $ResourceKey
    $endTime = (Get-Date).ToUniversalTime()
    $startTime = $endTime.AddHours(-24)
    $aggregation = $settings.Aggregation
    $grain = $settings.TimeGrain
    try {
        $metric = Invoke-WithRetry -Operation "Get-AzMetric $MetricName" -ScriptBlock {
            Get-AzMetric -ResourceId $ResourceId -MetricName $MetricName -StartTime $startTime -EndTime $endTime -TimeGrain $grain -AggregationType $aggregation -ErrorAction Stop -WarningAction SilentlyContinue
        }
    }
    catch {
        Add-ErrorRow -SubscriptionId $SubscriptionId -Module $Module -ResourceKey $ResourceKey -Operation "Get-AzMetric $MetricName" -Message $_.Exception.Message
        return $null
    }
    $max = $null
    foreach ($m in $metric) {
        foreach ($point in @(Get-Prop $m 'Data')) {
            $v = Get-Prop $point $aggregation
            if ($null -ne $v) {
                $d = [double]$v
                if ($null -eq $max -or $d -gt $max) { $max = $d }
            }
        }
    }
    if ($null -eq $max) {
        Add-ErrorRow -SubscriptionId $SubscriptionId -Module $Module -ResourceKey $ResourceKey -Operation "Get-AzMetric $MetricName" -Message "Metric returned no data points ($aggregation, last 24h); column left blank."
        return $null
    }
    return $max
}

function Resolve-NetworkAccess {
    <# Exactly one of VNetInjected, PrivateEndpointOnly, PrivateEndpoint+Public, VNetRules,
       PublicFirewall (IP rules only, including default Deny with zero rules), Public,
       PublicDisabled (public access disabled and no private endpoint), N/A. #>
    param(
        [bool]$HasNetworkSurface = $true,
        [bool]$VNetInjected = $false,
        [int]$PrivateEndpointCount = 0,
        [string]$PublicNetworkAccess,
        [string]$DefaultAction,
        [int]$VNetRuleCount = 0,
        [int]$IpRuleCount = 0
    )
    if (-not $HasNetworkSurface) { return 'N/A' }
    if ($VNetInjected) { return 'VNetInjected' }
    $publicDisabled = ($PublicNetworkAccess -match '^(Disabled|SecuredByPerimeter)$')
    if ($PrivateEndpointCount -gt 0) {
        if ($publicDisabled) { return 'PrivateEndpointOnly' }
        return 'PrivateEndpoint+Public'
    }
    if ($publicDisabled) { return 'PublicDisabled' }
    if ($DefaultAction -eq 'Deny') {
        if ($VNetRuleCount -gt 0) { return 'VNetRules' }
        return 'PublicFirewall'
    }
    return 'Public'
}

