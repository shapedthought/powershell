                    -Region (Get-Prop $p 'Location') -ResourceName "$sn/$pName" -ResourceType 'Microsoft.Sql/servers/elasticPools' -Tags (Get-Prop $p 'Tags') -Candidate $script:WorkloadMap.sqldb
                $rec.Net.InheritFrom = $srvId
