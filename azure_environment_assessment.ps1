function Get-NetworkBackbone {
    <# Collects vNets/subnets, private endpoints, NICs and public IPs of one subscription into the
       global lookups (keyed on lower-cased resource ID). A failure to list vNets is treated as the
       subscription being unreadable and is rethrown. #>
    param($Subscription)
    $subId = [string]$Subscription.Id
    $vnets = @(Invoke-WithRetry -Operation 'Get-AzVirtualNetwork' -ScriptBlock { Get-AzVirtualNetwork -ErrorAction Stop })
    foreach ($vn in $vnets) {
        $vnId = [string]$vn.Id
        $vnKey = ConvertTo-Lower $vnId
        $vnRg = [string](Get-Prop $vn 'ResourceGroupName')
        $script:State.VNets[$vnKey] = @{ Id = $vnId; Name = [string]$vn.Name; ResourceGroup = $vnRg; SubscriptionId = $subId; Region = (Format-Region $vn.Location) }
        $script:State.VNetRaw.Add(@{ VNet = $vn; Subscription = $Subscription })
        foreach ($sn in @(Get-Prop $vn 'Subnets')) {
            $prefixes = New-List
            foreach ($p in @(Get-Prop $sn 'AddressPrefix')) { if ($p -and -not $prefixes.Contains([string]$p)) { $prefixes.Add([string]$p) } }
            foreach ($p in @(Get-Prop $sn 'AddressPrefixes')) { if ($p -and -not $prefixes.Contains([string]$p)) { $prefixes.Add([string]$p) } }
            $script:State.Subnets[(ConvertTo-Lower $sn.Id)] = @{
                Id = [string]$sn.Id; Name = [string]$sn.Name; VNetId = $vnId; VNetName = [string]$vn.Name
                VNetResourceGroup = $vnRg; VNetSubscriptionId = $subId; Prefixes = $prefixes; Region = (Format-Region $vn.Location)
            }
        }
    }
    Write-Step ("    {0} virtual network(s)" -f $vnets.Count)

    try {
        $nics = @(Invoke-WithRetry -Operation 'Get-AzNetworkInterface' -ScriptBlock { Get-AzNetworkInterface -ErrorAction Stop })
        foreach ($nic in $nics) {
            $ipcs = @(Get-Prop $nic 'IpConfigurations')
            $primary = $null
            foreach ($ipc in $ipcs) { if (Get-Prop $ipc 'Primary') { $primary = $ipc; break } }
            if ($null -eq $primary -and $ipcs.Count -gt 0) { $primary = $ipcs[0] }
            $versions = @{}
            $publicIpId = ''
            foreach ($ipc in $ipcs) {
                $versions[(ConvertTo-Lower $ipc.Id)] = [string](Get-Prop $ipc 'PrivateIpAddressVersion')
                $pip = [string](Get-Prop $ipc 'PublicIpAddress.Id')
                if ($pip -and -not $publicIpId) { $publicIpId = $pip }
            }
            $script:State.Nics[(ConvertTo-Lower $nic.Id)] = @{
                Id = [string]$nic.Id; Name = [string]$nic.Name
                SubnetId = [string](Get-Prop $primary 'Subnet.Id')
                PrivateIp = [string](Get-Prop $primary 'PrivateIpAddress')
                PublicIpId = $publicIpId
                IpVersions = $versions
            }
        }
    }
    catch { Add-ErrorRow -SubscriptionId $subId -Module 'vnet' -Operation 'Get-AzNetworkInterface' -Message $_.Exception.Message }

    try {
        $pes = @(Invoke-WithRetry -Operation 'Get-AzPrivateEndpoint' -ScriptBlock { Get-AzPrivateEndpoint -ErrorAction Stop })
        foreach ($pe in $pes) {
            $nicIds = @(Get-Prop $pe 'NetworkInterfaces' | ForEach-Object { [string]$_.Id })
            $privateIp = ''
            $ipCount = 0
            foreach ($n in $nicIds) {
                $nicInfo = $script:State.Nics[(ConvertTo-Lower $n)]
                if ($nicInfo) { if (-not $privateIp) { $privateIp = $nicInfo.PrivateIp }; $ipCount += [math]::Max(1, $nicInfo.IpVersions.Count) }
            }
            if (-not $privateIp) {
                foreach ($c in @(Get-Prop $pe 'CustomDnsConfigs')) { foreach ($ip in @(Get-Prop $c 'IpAddresses')) { if (-not $privateIp) { $privateIp = [string]$ip } } }
            }
            if ($ipCount -eq 0) { $ipCount = 1 }
            $connections = @(Get-Prop $pe 'PrivateLinkServiceConnections') + @(Get-Prop $pe 'ManualPrivateLinkServiceConnections')
            $subnetId = [string](Get-Prop $pe 'Subnet.Id')
            $info = @{ Id = [string]$pe.Id; Name = [string]$pe.Name; SubnetId = $subnetId; PrivateIp = $privateIp; NicIds = $nicIds; IpCount = $ipCount }
            # Distinct IPv4 IP-configuration IDs of this private endpoint's NIC(s), for UsedIPs de-duplication.
            $ipcIds = New-List
            foreach ($n in $nicIds) {
                $nicInfo = $script:State.Nics[(ConvertTo-Lower $n)]
                if ($nicInfo) { foreach ($k in $nicInfo.IpVersions.Keys) { if ($nicInfo.IpVersions[$k] -ne 'IPv6') { $ipcIds.Add([string]$k) } } }
            }
            if ($ipcIds.Count -eq 0) { for ($i = 0; $i -lt $ipCount; $i++) { $ipcIds.Add((ConvertTo-Lower $info.Id) + '#ip' + $i) } }
            $info.IpConfigIds = $ipcIds
            $sk = ConvertTo-Lower $subnetId
            if ($sk) {
                if (-not $script:State.PeBySubnet.ContainsKey($sk)) { $script:State.PeBySubnet[$sk] = New-List }
                $script:State.PeBySubnet[$sk].Add($info)
            }
            foreach ($conn in $connections) {
                if ($null -eq $conn) { continue }
                $target = ConvertTo-Lower ([string](Get-Prop $conn 'PrivateLinkServiceId'))
                if (-not $target) { continue }
                # Only an Approved connection makes the target reachable through this endpoint; pending,
                # rejected or disconnected endpoints still consume subnet IPs (PeBySubnet above).
                if ([string](Get-Prop $conn 'PrivateLinkServiceConnectionState.Status') -ne 'Approved') { continue }
                $entry = @{ Id = $info.Id; Name = $info.Name; SubnetId = $subnetId; PrivateIp = $privateIp; GroupIds = @(Get-Prop $conn 'GroupIds') }
                if (-not $script:State.PeByTarget.ContainsKey($target)) { $script:State.PeByTarget[$target] = New-List }
                $script:State.PeByTarget[$target].Add($entry)
            }
        }
        Write-Step ("    {0} private endpoint(s)" -f $pes.Count)
    }
    catch {
        $script:State.PeListingFailed.Add($subId)
        Add-ErrorRow -SubscriptionId $subId -Module 'vnet' -Operation 'Get-AzPrivateEndpoint' -Message $_.Exception.Message
    }

    try {
        $pips = @(Invoke-WithRetry -Operation 'Get-AzPublicIpAddress' -ScriptBlock { Get-AzPublicIpAddress -ErrorAction Stop })
        foreach ($pip in $pips) { $script:State.PublicIps[(ConvertTo-Lower $pip.Id)] = @{ IpAddress = [string](Get-Prop $pip 'IpAddress') } }
    }
    catch { Add-ErrorRow -SubscriptionId $subId -Module 'vnet' -Operation 'Get-AzPublicIpAddress' -Message $_.Exception.Message }
}

function Get-VNetInventory {
    <# Builds virtual_networks and subnets records from the backbone of every subscription. Runs after
       pass 1 so private endpoint NICs from any subscription are known. #>
    $records = New-List
    $reserved = @('gatewaysubnet', 'azurefirewallsubnet', 'azurebastionsubnet', 'routeserversubnet', 'azurefirewallmanagementsubnet')
    foreach ($entry in $script:State.VNetRaw) {
        $vn = $entry.VNet
        $sub = $entry.Subscription
        try {
            $rec = New-WorkloadRecord -Output 'virtual_networks' -Module 'vnet' -ResourceId $vn.Id -Subscription $sub -ResourceGroup $vn.ResourceGroupName `
                -Region $vn.Location -ResourceName $vn.Name -ResourceType 'Microsoft.Network/virtualNetworks' -Tags (Get-Prop $vn 'Tag', 'Tags') -Candidate $script:WorkloadMap.vnet
            $rec.Net.ExplicitAccess = 'N/A'
            $rec.Net.SelfVNetId = $vn.Id
            $peerNames = New-List
            $peerStates = New-List
            $peerings = @(Get-Prop $vn 'VirtualNetworkPeerings')
            foreach ($p in $peerings) {
                $remoteId = [string](Get-Prop $p 'RemoteVirtualNetwork.Id')
                $remote = $script:State.VNets[(ConvertTo-Lower $remoteId)]
                if ($remote) { $peerNames.Add($remote.Name) } else { $peerNames.Add((Get-NameFromId $remoteId)) }
                $peerStates.Add([string](Get-Prop $p 'PeeringState'))
            }
            $c = $rec.Columns
            $c.AddressSpaces = Join-List (Get-Prop $vn 'AddressSpace.AddressPrefixes')
            $c.DnsServers = Join-List (Get-Prop $vn 'DhcpOptions.DnsServers')
            $c.DdosProtectionEnabled = [bool](Get-Prop $vn 'EnableDdosProtection')
            $c.DdosProtectionPlan = Get-NameFromId ([string](Get-Prop $vn 'DdosProtectionPlan.Id'))
            $c.PeeringCount = $peerings.Count
            $c.PeeredVNets = $peerNames -join ';'
            $c.PeeringStates = $peerStates -join ';'
            $c.SubnetCount = Get-Count (Get-Prop $vn 'Subnets')
            $vnPe = 0
            foreach ($sn in @(Get-Prop $vn 'Subnets')) { $l = $script:State.PeBySubnet[(ConvertTo-Lower $sn.Id)]; if ($l) { $vnPe += $l.Count } }
            $rec.Net.SelfPeCount = $vnPe
            $records.Add($rec)
        }
        catch { Add-ErrorRow -SubscriptionId $sub.Id -Module 'vnet' -ResourceKey $vn.Id -Operation 'BuildVNetRow' -Message $_.Exception.Message }

        foreach ($sn in @(Get-Prop $vn 'Subnets')) {
            try {
                $info = $script:State.Subnets[(ConvertTo-Lower $sn.Id)]
                $srec = New-WorkloadRecord -Output 'subnets' -Module 'vnet' -ResourceId $sn.Id -Subscription $sub -ResourceGroup $vn.ResourceGroupName `
                    -Region $vn.Location -ResourceName $sn.Name -ResourceType 'Microsoft.Network/virtualNetworks/subnets' -Tags (Get-Prop $vn 'Tag', 'Tags') -Candidate $script:WorkloadMap.vnet
                $srec.Net.ExplicitAccess = 'N/A'
                $srec.Net.SelfSubnetId = $sn.Id
                $v4 = New-List; $v6 = New-List
                foreach ($p in $info.Prefixes) { if ($p -match ':') { $v6.Add($p) } else { $v4.Add($p) } }
                $total = 0; $lengths = New-List
                foreach ($p in $v4) {
                    if ($p -match '/(\d+)$') { $len = [int]$Matches[1]; $lengths.Add($len); $total += [math]::Pow(2, 32 - $len) }
                }
                # UsedIPs: distinct IPv4 IP-configuration IDs across the subnet's IP configurations and
                # its private endpoints' NIC IP configurations (the two sets overlap).
                $ipcSet = @{}
                foreach ($ipc in @(Get-Prop $sn 'IpConfigurations')) {
                    $ipcId = ConvertTo-Lower ([string]$ipc.Id)
                    $nicId = $ipcId -replace '/ipconfigurations/.*$', ''
                    $nicInfo = $script:State.Nics[$nicId]
                    if ($nicInfo -and $nicInfo.IpVersions.ContainsKey($ipcId) -and $nicInfo.IpVersions[$ipcId] -eq 'IPv6') { continue }
                    $ipcSet[$ipcId] = $true
                }
                $peList = $script:State.PeBySubnet[(ConvertTo-Lower $sn.Id)]
                $peCount = 0
                if ($peList) {
                    foreach ($pe in $peList) {
                        $peCount++
                        foreach ($k in $pe.IpConfigIds) { $ipcSet[$k] = $true }
                    }
                }
                $used = $ipcSet.Count
                $srec.Net.SelfPeCount = $peCount
                # Azure reserves 5 addresses in every IPv4 prefix.
                $available = 0
                if ($total -gt 0) { $available = [math]::Max(0, $total - (5 * $v4.Count) - $used) }
                $delegations = @(Get-Prop $sn 'Delegations' | ForEach-Object { [string](Get-Prop $_ 'ServiceName') })
                $services = @(Get-Prop $sn 'ServiceEndpoints' | ForEach-Object { [string](Get-Prop $_ 'Service') })
                $c = $srec.Columns
                $c.PrefixLength = $lengths -join ';'
                $c.IPv6Prefixes = $v6 -join ';'
                $c.TotalIPs = [int64]$total
                $c.UsedIPs = $used
                $c.AvailableIPs = [int64]$available
                $c.NsgName = Get-NameFromId ([string](Get-Prop $sn 'NetworkSecurityGroup.Id'))
                $c.RouteTableName = Get-NameFromId ([string](Get-Prop $sn 'RouteTable.Id'))
                $c.NatGateway = Get-NameFromId ([string](Get-Prop $sn 'NatGateway.Id'))
                $c.ServiceEndpoints = Join-List $services
                $c.HasStorageServiceEndpoint = ($services -contains 'Microsoft.Storage')
                $c.HasStorageGlobalServiceEndpoint = ($services -contains 'Microsoft.Storage.Global')
                $c.Delegations = Join-List $delegations
                $c.PrivateEndpointNetworkPolicies = [string](Get-Prop $sn 'PrivateEndpointNetworkPolicies')
                $c.PrivateEndpointsInSubnet = $peCount
                $c.CanHostVeeamWorkers = (($delegations.Count -eq 0) -and ($reserved -notcontains ([string]$sn.Name).ToLowerInvariant()) -and ($available -ge 3))
                $records.Add($srec)
            }
            catch { Add-ErrorRow -SubscriptionId $sub.Id -Module 'vnet' -ResourceKey $sn.Id -Operation 'BuildSubnetRow' -Message $_.Exception.Message }
        }
    }
    return , $records
}

