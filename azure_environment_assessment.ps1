<#
.SYNOPSIS
    Read-only discovery of an Azure estate ahead of designing a Veeam backup solution.

.DESCRIPTION
    UNOFFICIAL COMMUNITY SCRIPT. This is not a Veeam tool and it carries no support.

    GENERATED FROM A PROMPT. This script was generated by an LLM (Claude) from the
    VBAz-AzureEnvironmentAssessment prompt in the awesome-veeam-prompts repository:
      https://github.com/shapedthought/awesome-veeam-prompts/tree/main/VBAz-AzureEnvironmentAssessment
    That prompt, and its workload map, are the source of truth. To change behaviour,
    update the prompt and regenerate, or edit here and feed the change back into it.
    It passed its Pester tests with Az cmdlets mocked, but has NOT yet been run
    against a real Azure tenant. Review it, and test it on one subscription first.

    Inventories the workloads listed in the workload map (VMs and disks, Azure SQL Database,
    SQL Managed Instance, Cosmos DB, Azure Files, Blob storage accounts, virtual networks and,
    optionally, AKS, Azure VMware Solution and Microsoft Entra ID) and places every resource in
    its environment: tenant, subscription, resource group, region, availability zone, virtual
    network and subnet, plus how it is reached on the network (NetworkAccess).

    Collection runs in three passes:
      Pass 1  network backbone (vNets/subnets, private endpoints, NICs, public IPs) for EVERY
              subscription;
      Pass 2  the selected workload modules for every subscription;
      Pass 3  placement of every workload row against the backbone of ALL subscriptions, so a
              private endpoint or vNet that lives in a hub subscription is still resolved.

    The script is read-only. It uses management-plane GET operations only (Az cmdlets, Azure
    Monitor metrics, and Microsoft Graph GETs for the optional entra module). It never lists
    storage account keys, never generates SAS tokens, never calls data-plane endpoints (no blob
    listing, no SQL or Cosmos DB queries) and never creates, modifies or tags anything.

    REQUIRED ROLES / SCOPES (minimum)
      - Reader on each subscription to assess (Reader includes Azure Monitor metrics read).
      - Backup Reader on the subscriptions / vaults for -BackupAssessment.
      - Microsoft Graph delegated read scopes for the entra module:
        Directory.Read.All and Policy.Read.All (consented for the signed-in user).

    OUTPUT (all CSV files are always written, header-only when empty)
      vms.csv, disks.csv, sql_databases.csv, sql_elastic_pools.csv, sql_managed_instances.csv,
      sql_mi_databases.csv, cosmos_accounts.csv, file_shares.csv, storage_accounts.csv,
      virtual_networks.csv, subnets.csv, aks_clusters.csv, aks_node_pools.csv,
      avs_private_clouds.csv, entra_tenant.csv, other_resources_summary.csv,
      network_attachments.csv, backup_vaults.csv, backup_items.csv, backup_policies.csv,
      backup_jobs.csv, backup_coverage.csv, environment_summary.csv, region_summary.csv,
      errors.csv, environment_map.json, manifest.json.

    TESTING: the script can be dot-sourced (". .\azure_environment_assessment.ps1") without running;
    the main function Invoke-AzureEnvironmentAssessment only runs automatically when the file is
    executed rather than dot-sourced.

.PARAMETER Modules
    Modules to run: vm, sqldb, sqlmi, cosmos, files, blob, vnet, aks, avs, entra, other, or all.
    Default: vm, sqldb, sqlmi, cosmos, files, blob, vnet, other. aks, avs and entra are opt-in.
    vnet always runs because it is the placement backbone for every other module.

.PARAMETER SubscriptionId
    Optional list of subscription IDs to assess. Default: every enabled subscription the account can see.

.PARAMETER TenantId
    Optional tenant ID, passed to Connect-AzAccount and used to filter subscriptions.

.PARAMETER UseDeviceAuthentication
    Use device code authentication (hosts without a browser).

.PARAMETER UseExistingContext
    Skip Connect-AzAccount when an Az context already exists (for example in Azure Cloud Shell).

.PARAMETER BackupAssessment
    Also collect existing native Azure Backup configuration (Recovery Services vaults and Backup vaults).

.PARAMETER SkipMetrics
    Skip Azure Monitor calls. Faster, but used-size columns are left blank.

.PARAMETER TagNames
    Tag keys to emit as extra columns (named Tag_<key>) on every resource row, for example
    Environment, Application, CostCentre. Default: none.

.PARAMETER Anonymise
    Replace sensitive strings (names, resource IDs, IP addresses, DNS servers, tag values) with the
    first 12 hex characters of HMAC-SHA256(salt, value). Tenant ID, subscription ID, regions,
    zones, SKUs, sizes, counts, flags, states and timestamps are kept.

.PARAMETER AnonymiseSalt
    Optional salt for -Anonymise. When omitted a random 32-byte salt is generated per run, so two
    runs can only be correlated when the same salt is supplied. The salt is never written anywhere.

.PARAMETER OutputPath
    Output folder. Default: .\AzureAssessment_<yyyyMMdd_HHmmss>.

.PARAMETER AcceptDisclaimer
    Skip the interactive consent prompt.

.EXAMPLE
    .\azure_environment_assessment.ps1 -Modules all -BackupAssessment
    Full run: every module, including aks, avs and entra, plus existing native backup configuration.

.EXAMPLE
    .\azure_environment_assessment.ps1 -UseExistingContext -AcceptDisclaimer -OutputPath $HOME/clouddrive/assessment
    Azure Cloud Shell run, reusing the Cloud Shell sign-in and writing to the persistent clouddrive.

.EXAMPLE
    .\azure_environment_assessment.ps1 -SubscriptionId 00000000-0000-0000-0000-000000000000 -Modules vm,vnet
    Single-subscription run collecting only VMs and the network backbone.

.EXAMPLE
    .\azure_environment_assessment.ps1 -Anonymise -AnonymiseSalt 'customer-x-2026' -TagNames Environment
    Anonymised run. Supply the same salt to correlate two runs.

.NOTES
    Targets Windows PowerShell 5.1 and PowerShell 7.2+, Az 12.0 or later, Azure Cloud Shell.
