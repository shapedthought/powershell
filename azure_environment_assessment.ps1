                $c.ZoneRedundant = Get-Prop $p 'ZoneRedundant'
                $records.Add($rec)
            }
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'sqldb' -ResourceKey $srvId -Operation 'ProcessSqlServer' -Message $_.Exception.Message }
    }
