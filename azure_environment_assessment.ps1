function Get-AvsInventory {
    <# Management plane only; never contacts vCenter. #>
    param($Subscription)
    $subId = [string]$Subscription.Id
    $records = New-List
    $clouds = @(Invoke-WithRetry -Operation 'Get-AzVMwarePrivateCloud' -ScriptBlock { Get-AzVMwarePrivateCloud -ErrorAction Stop })
    foreach ($pc in $clouds) {
        $pid_ = [string]$pc.Id
        try {
            $rg = [string](Get-Prop $pc 'ResourceGroupName')
            if (-not $rg) { $rg = (ConvertFrom-ResourceId $pid_).ResourceGroup }
            $name = [string]$pc.Name
            $rec = New-WorkloadRecord -Output 'avs_private_clouds' -Module 'avs' -ResourceId $pid_ -Subscription $Subscription -ResourceGroup $rg `
                -Region $pc.Location -ResourceName $name -ResourceType 'Microsoft.AVS/privateClouds' -Tags (Get-Prop $pc 'Tag', 'Tags') -Candidate $script:WorkloadMap.avs
            $rec.Net.VNetInjected = $true
            # Hosts per cluster come from ONE listing (Get-AzVMwareCluster). Whether that listing includes
            # the management cluster is not certain, so the private cloud's management cluster size is
            # added only when its cluster ID is known and absent from the listing, or when the listing is
            # empty or failed (fallback). This avoids double counting either way.
            $names = New-List; $hosts = New-List; $total = 0
            $mgmt = Get-Prop $pc 'ManagementClusterSize', 'ManagementCluster.ClusterSize'
            $mgmtId = [string](Get-Prop $pc 'ManagementClusterId', 'ManagementCluster.ClusterId')
            $listed = @()
            $listingOk = $true
            try { $listed = @(Invoke-WithRetry -Operation 'Get-AzVMwareCluster' -ScriptBlock { Get-AzVMwareCluster -PrivateCloudName $name -ResourceGroupName $rg -ErrorAction Stop }) }
            catch { $listingOk = $false; Add-ErrorRow -SubscriptionId $subId -Module 'avs' -ResourceKey $pid_ -Operation 'Get-AzVMwareCluster' -Message $_.Exception.Message }
            $mgmtListed = $false
            foreach ($cl in $listed) { if ($mgmtId -and [string](Get-Prop $cl 'ClusterId') -eq $mgmtId) { $mgmtListed = $true } }
            $addMgmt = ($null -ne $mgmt) -and ((-not $listingOk) -or $listed.Count -eq 0 -or ($mgmtId -and -not $mgmtListed))
            if ($addMgmt) { $names.Add('(management)'); $hosts.Add([string]$mgmt); $total += [int]$mgmt }
            foreach ($cl in $listed) {
                $size = Get-Prop $cl 'ClusterSize', 'Size'
                $names.Add([string]$cl.Name); $hosts.Add([string]$size)
                if ($null -ne $size) { $total += [int]$size }
            }
            $gr = @()
            try { $gr = @(Invoke-WithRetry -Operation 'Get-AzVMwareGlobalReachConnection' -ScriptBlock { Get-AzVMwareGlobalReachConnection -PrivateCloudName $name -ResourceGroupName $rg -ErrorAction Stop }) }
            catch { Add-ErrorRow -SubscriptionId $subId -Module 'avs' -ResourceKey $pid_ -Operation 'Get-AzVMwareGlobalReachConnection' -Message $_.Exception.Message }
            $c = $rec.Columns
            $c.SkuName = [string](Get-Prop $pc 'SkuName', 'Sku.Name')
            $c.ClusterCount = $names.Count
            $clusterNames = New-List
            foreach ($n in $names) { if ($n -ne '(management)') { $clusterNames.Add($n) } }
            $c.ClusterNames = $clusterNames -join ';'
            $c.HostCountPerCluster = $hosts -join ';'
            $c.TotalHosts = $total
            $c.ManagementNetwork = [string](Get-Prop $pc 'NetworkBlock')
            $c.ExpressRouteConnected = [bool](Get-Prop $pc 'CircuitExpressRouteId', 'Circuit.ExpressRouteId')
            $c.GlobalReachConnectionCount = $gr.Count
            $c.GlobalReachStates = Join-List ($gr | ForEach-Object { [string](Get-Prop $_ 'CircuitConnectionStatus', 'Status') })
            $records.Add($rec)
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'avs' -ResourceKey $pid_ -Operation 'BuildAvsRow' -Message $_.Exception.Message }
    }
    Write-Step ("    {0} AVS private cloud(s)" -f $clouds.Count)
    return , $records
}

function Get-GraphCount {
    param([string]$RelativeUri)
    $uri = 'https://graph.microsoft.com/v1.0/' + $RelativeUri
    $total = 0
    while ($uri) {
        $page = Invoke-WithRetry -Operation "Graph GET $RelativeUri" -ScriptBlock { Invoke-MgGraphRequest -Method GET -Uri $uri -ErrorAction Stop }
        $total += Get-Count (Get-Prop $page 'value')
        # Literal key: Get-Prop splits paths on '.', which would never find '@odata.nextLink'.
        $next = $null
        if ($page -is [System.Collections.IDictionary]) { if ($page.Contains('@odata.nextLink')) { $next = $page['@odata.nextLink'] } }
        elseif ($null -ne $page) { $np = $page.PSObject.Properties['@odata.nextLink']; if ($np) { $next = $np.Value } }
        $uri = [string]$next
    }
    return $total
}

function Get-EntraInventory {
    <# Tenant-level counts via Microsoft Graph GETs (read scopes only). #>
    param([string]$TenantId, [switch]$UseDeviceAuthentication)
    $records = New-List
    if (-not $TenantId) { throw 'Assessed tenant ID is unknown; Entra counts not collected (they could not be attributed to a tenant).' }
    # An existing Graph context may belong to a different tenant: reconnect to the assessed tenant, and
    # refuse to label another tenant's data with this tenant's ID.
    $ctx = Get-MgContext
    if (-not $ctx -or ([string](Get-Prop $ctx 'TenantId')) -ne $TenantId) {
        if ($ctx) { Write-Step '    Graph context belongs to another tenant; reconnecting to the assessed tenant.' -Level Warning }
        $p = @{ Scopes = @('Directory.Read.All', 'Policy.Read.All'); TenantId = $TenantId; ErrorAction = 'Stop' }
        if ($UseDeviceAuthentication) { $p.UseDeviceCode = $true }
        Connect-MgGraph @p | Out-Null
        $ctx = Get-MgContext
        if (-not $ctx -or ([string](Get-Prop $ctx 'TenantId')) -ne $TenantId) {
            throw 'Microsoft Graph context is not for the assessed tenant after reconnecting; Entra counts not collected.'
        }
    }
    $domain = ''
    try {
        $org = @(Invoke-WithRetry -Operation 'Get-MgOrganization' -ScriptBlock { Get-MgOrganization -ErrorAction Stop })[0]
        foreach ($d in @(Get-Prop $org 'VerifiedDomains')) { if ((Get-Prop $d 'IsDefault') -eq $true) { $domain = [string]$d.Name } }
    }
    catch { Add-ErrorRow -Module 'entra' -Operation 'Get-MgOrganization' -Message $_.Exception.Message }
    $pseudoSub = [pscustomobject]@{ Id = ''; Name = ''; TenantId = $TenantId }
    $rec = New-WorkloadRecord -Output 'entra_tenant' -Module 'entra' -ResourceId $TenantId -Subscription $pseudoSub -ResourceGroup '' -Region '' `
        -ResourceName $domain -ResourceType 'Microsoft Entra ID tenant' -Tags $null -Candidate $script:WorkloadMap.entra
    $rec.Net.HasSurface = $false
    $c = $rec.Columns
    $c.TenantDomain = $domain
    $queries = [ordered]@{
        Users = 'users?$select=id&$top=999'; Groups = 'groups?$select=id&$top=999'; Applications = 'applications?$select=id&$top=999'
        ServicePrincipals = 'servicePrincipals?$select=id&$top=999'; ConditionalAccessPolicies = 'identity/conditionalAccess/policies?$select=id'
        AdministrativeUnits = 'directory/administrativeUnits?$select=id&$top=999'
    }
    foreach ($q in $queries.Keys) {
        try { $c[$q] = Get-GraphCount -RelativeUri $queries[$q] }
        catch { Add-ErrorRow -Module 'entra' -Operation "Graph count $q" -Message $_.Exception.Message }
    }
    $records.Add($rec)
    return , $records
}

function Get-OtherResourceSummary {
    <# One row per resource type per region with a count, for gap analysis. Includes workload-map
       types too (flagged InWorkloadMap = true) so the census is complete. #>
    param($Subscription)
    $records = New-List
    $resources = Get-SubscriptionResources -Subscription $Subscription
    $groups = @{}
    $order = New-List
    foreach ($r in $resources) {
        $t = [string]$r.ResourceType
        $loc = Format-Region ([string]$r.Location)
        $key = $loc + '|' + $t.ToLowerInvariant()
        if (-not $groups.ContainsKey($key)) { $groups[$key] = @{ Region = $loc; Type = $t; Count = 0 }; $order.Add($key) }
        $groups[$key].Count++
    }
    foreach ($key in $order) {
        $g = $groups[$key]
        $lt = $g.Type.ToLowerInvariant()
        $gap = ''
        if ($script:GapDataServices.ContainsKey($lt)) { $gap = 'Data service not in workload map: ' + $script:GapDataServices[$lt] }
        $records.Add([pscustomobject]@{
                Output = 'other_resources_summary'; Plain = $true
                Row    = [pscustomobject][ordered]@{
                    SubscriptionId = [string]$Subscription.Id; SubscriptionName = [string]$Subscription.Name; Region = $g.Region
                    ResourceType = $g.Type; Count = $g.Count; InWorkloadMap = $script:WorkloadMapTypes.ContainsKey($lt); GapNote = $gap
                }
            })
    }
    Write-Step ("    {0} resource(s) in {1} type/region group(s)" -f @($resources).Count, $order.Count)
    return , $records
}

