function ConvertTo-MaskedRow {
    param($Row)
    $out = [ordered]@{}
    foreach ($p in $Row.PSObject.Properties) {
        $n = $p.Name; $v = $p.Value
        if ($null -eq $v -or [string]$v -eq '') { $out[$n] = $v; continue }
        if ($script:MaskIdColumns.Contains($n)) { $out[$n] = Get-Mask $v }
        elseif ($script:MaskNameColumns.Contains($n)) { $out[$n] = Get-MaskedList ([string]$v) -Kind Name }
        elseif ($script:MaskIpColumns.Contains($n)) { $out[$n] = Get-MaskedList ([string]$v) -Kind Name }
        elseif ($script:MaskPrefixColumns.Contains($n)) { $out[$n] = Get-MaskedList ([string]$v) -Kind Prefix }
        elseif ($n -like 'Tag_*') { $out[$n] = Get-Mask $v -CaseSensitive }
        elseif ($n -eq 'Message') { $out[$n] = Protect-Message ([string]$v) }
        elseif ($v -is [string] -and $v -match '(?i)/subscriptions/|/providers/') { $out[$n] = Get-Mask $v }  # safety net: never a raw ID
        else { $out[$n] = $v }
    }
    return [pscustomobject]$out
}

function Invoke-OutputMasking {
    if (-not $script:AnonymiseEnabled) { return }
    foreach ($k in $script:OutputOrder) {
        $list = $script:State.Outputs[$k]
        for ($i = 0; $i -lt $list.Count; $i++) { $list[$i] = ConvertTo-MaskedRow $list[$i] }
    }
}

function Get-WorkerCapableIndex {
    $idx = @{}
    $regions = @{}
    foreach ($s in $script:State.Outputs['subnets']) {
        if ([string]$s.CanHostVeeamWorkers -eq 'True') {
            $vk = ($s.VNetSubscriptionId + '|' + $s.VNetResourceGroup + '|' + $s.VNetName).ToLowerInvariant()
            if ($idx.ContainsKey($vk)) { $idx[$vk]++ } else { $idx[$vk] = 1 }
            if ($regions.ContainsKey($s.Region)) { $regions[$s.Region]++ } else { $regions[$s.Region] = 1 }
        }
    }
    return @{ ByVNet = $idx; ByRegion = $regions }
}

function New-SummaryCounters {
    $h = [ordered]@{}
    foreach ($src in $script:SummarySources.Values) {
        $h[$src.Count] = 0
        $h[$src.Size] = 0.0
        $h['__known_' + $src.Size] = 0
    }
    return $h
}

function Add-SummaryCounters {
    <# Copies counters into a summary row: capacity is blank when no value in the bucket is known, and
       <Module>CapacityComplete says whether every resource in the bucket had a value. #>
    param($Row, $Counters)
    foreach ($src in $script:SummarySources.Values) {
        $n = $Counters[$src.Count]
        $known = $Counters['__known_' + $src.Size]
        $Row[$src.Count] = $n
        if ($n -gt 0 -and $known -eq 0) { $Row[$src.Size] = '' }
        else { $Row[$src.Size] = [math]::Round($Counters[$src.Size], 2) }
        $Row[$src.Complete] = ($known -eq $n)
    }
}

function Build-Summaries {
    <# environment_summary (SubscriptionId x Region x vNet) and region_summary, from the final rows. #>
    $worker = Get-WorkerCapableIndex
    $env = @{}; $envOrder = New-List
    $regionData = @{}; $regionOrder = New-List
    foreach ($out in $script:SummarySources.Keys) {
        $src = $script:SummarySources[$out]
        foreach ($row in $script:State.Outputs[$out]) {
            $vnetName = [string]$row.VNetName
            if (-not $vnetName) { $vnetName = '(none)' }
            $k = ($row.SubscriptionId + '|' + $row.Region + '|' + $row.VNetSubscriptionId + '|' + $row.VNetResourceGroup + '|' + $vnetName).ToLowerInvariant()
            if (-not $env.ContainsKey($k)) {
                $env[$k] = @{
                    Head = [ordered]@{ SubscriptionId = $row.SubscriptionId; SubscriptionName = $row.SubscriptionName; Region = $row.Region
                        VNetSubscriptionId = $row.VNetSubscriptionId; VNetResourceGroup = $row.VNetResourceGroup; VNetName = $vnetName
                    }
                    Mix = [ordered]@{}; Counters = (New-SummaryCounters)
                }
                $envOrder.Add($k)
            }
            $e = $env[$k]
            $na = [string]$row.NetworkAccess
            if ($e.Mix.Contains($na)) { $e.Mix[$na]++ } else { $e.Mix[$na] = 1 }
            $e.Counters[$src.Count]++
            $size = $null
            if ($src.Column) { $size = $row.($src.Column) }
            if ($null -ne $size -and [string]$size -ne '') { $e.Counters[$src.Size] += [double]$size; $e.Counters['__known_' + $src.Size]++ }

            $rk = [string]$row.Region
            if (-not $regionData.ContainsKey($rk)) { $regionData[$rk] = @{ Subs = @{}; VNets = @{}; Counters = (New-SummaryCounters) }; $regionOrder.Add($rk) }
            $rd = $regionData[$rk]
            $rd.Subs[[string]$row.SubscriptionId] = $true
            if ($vnetName -ne '(none)') { $rd.VNets[($row.VNetSubscriptionId + '|' + $row.VNetResourceGroup + '|' + $vnetName).ToLowerInvariant()] = $true }
            $rd.Counters[$src.Count]++
            if ($null -ne $size -and [string]$size -ne '') { $rd.Counters[$src.Size] += [double]$size; $rd.Counters['__known_' + $src.Size]++ }
        }
    }
    foreach ($k in $envOrder) {
        $e = $env[$k]
        $r = [ordered]@{}
        foreach ($h in $e.Head.Keys) { $r[$h] = $e.Head[$h] }
        $r.NetworkAccessMix = (@($e.Mix.Keys | ForEach-Object { '{0}:{1}' -f $_, $e.Mix[$_] }) -join ';')
        Add-SummaryCounters -Row $r -Counters $e.Counters
        $wc = 0
        if ($e.Head.VNetName -ne '(none)') {
            $vk = ($e.Head.VNetSubscriptionId + '|' + $e.Head.VNetResourceGroup + '|' + $e.Head.VNetName).ToLowerInvariant()
            if ($worker.ByVNet.ContainsKey($vk)) { $wc = $worker.ByVNet[$vk] }
        }
        $r.WorkerCapableSubnets = $wc
        $script:State.Outputs['environment_summary'].Add([pscustomobject]$r)
    }
    foreach ($rk in $worker.ByRegion.Keys) { if (-not $regionData.ContainsKey($rk)) { $regionData[$rk] = @{ Subs = @{}; VNets = @{}; Counters = (New-SummaryCounters) }; $regionOrder.Add($rk) } }
    foreach ($rk in $regionOrder) {
        $rd = $regionData[$rk]
        $r = [ordered]@{ Region = $rk; Subscriptions = $rd.Subs.Count; VNets = $rd.VNets.Count }
        Add-SummaryCounters -Row $r -Counters $rd.Counters
        $wc = 0
        if ($worker.ByRegion.ContainsKey($rk)) { $wc = $worker.ByRegion[$rk] }
        $r.WorkerCapableSubnets = $wc
        $r.HasWorkerCapableSubnet = ($wc -gt 0)
        $script:State.Outputs['region_summary'].Add([pscustomobject]$r)
    }
}

function Build-EnvironmentMap {
    <# tenant -> subscriptions -> regions -> vNets -> subnets -> resources. Nesting (objects and arrays
       both count for ConvertTo-Json): root(0) Subscriptions[1] sub{2} Regions[3] region{4} VNets[5]
       vnet{6} Subnets[7] subnet{8} Resources[9] resource{10} -> exactly -Depth 10. #>
    $root = [ordered]@{ TenantId = $script:State.TenantId; TenantDomain = (Get-Mask $script:State.TenantDomain); Subscriptions = (New-List) }
    $idx = @{}
    $subnetInfo = @{}
    $getNode = {
        param([string]$SubId, [string]$SubName, [string]$Region, [string]$VSub, [string]$VRg, [string]$VName, [string]$SName)
        $sk = 's|' + $SubId
        if (-not $idx.ContainsKey($sk)) { $n = [ordered]@{ SubscriptionId = $SubId; SubscriptionName = $SubName; Regions = (New-List) }; $idx[$sk] = $n; $root.Subscriptions.Add($n) }
        $rk = $sk + '|' + $Region
        if (-not $idx.ContainsKey($rk)) {
            $n = [ordered]@{ Region = $Region; VNets = (New-List) }; $idx[$rk] = $n; $idx[$sk].Regions.Add($n)
            $none = [ordered]@{ VNetName = '(none)'; VNetSubscriptionId = ''; VNetResourceGroup = ''; Subnets = (New-List) }
            $idx[$rk + '|||(none)'] = $none; $n.VNets.Add($none)
        }
        if (-not $VName) { $VName = '(none)'; $VSub = ''; $VRg = '' }
        $vk = $rk + '|' + $VSub + '|' + $VRg + '|' + $VName
        if (-not $idx.ContainsKey($vk)) { $n = [ordered]@{ VNetName = $VName; VNetSubscriptionId = $VSub; VNetResourceGroup = $VRg; Subnets = (New-List) }; $idx[$vk] = $n; $idx[$rk].VNets.Add($n) }
        if (-not $SName) { $SName = '(none)' }
        $nk = $vk + '|' + $SName
        if (-not $idx.ContainsKey($nk)) {
            $info = $subnetInfo[($VSub + '|' + $VRg + '|' + $VName + '|' + $SName).ToLowerInvariant()]
            $prefix = ''; $canHost = $null
            if ($info) { $prefix = $info.Prefix; $canHost = $info.CanHost }
            $n = [ordered]@{ SubnetName = $SName; SubnetPrefix = $prefix; CanHostVeeamWorkers = $canHost; Resources = (New-List) }
            $idx[$nk] = $n; $idx[$vk].Subnets.Add($n)
        }
        return $idx[$nk]
    }
    foreach ($s in $script:State.Outputs['subnets']) {
        $subnetInfo[($s.VNetSubscriptionId + '|' + $s.VNetResourceGroup + '|' + $s.VNetName + '|' + $s.SubnetName).ToLowerInvariant()] = @{ Prefix = $s.SubnetPrefix; CanHost = $s.CanHostVeeamWorkers }
    }
    foreach ($s in $script:State.Outputs['subnets']) {
        [void](& $getNode $s.SubscriptionId $s.SubscriptionName $s.Region $s.VNetSubscriptionId $s.VNetResourceGroup $s.VNetName $s.SubnetName)
    }
    foreach ($out in $script:SummarySources.Keys) {
        $col = $script:SummarySources[$out].Column
        foreach ($row in $script:State.Outputs[$out]) {
            $node = & $getNode $row.SubscriptionId $row.SubscriptionName $row.Region $row.VNetSubscriptionId $row.VNetResourceGroup $row.VNetName $row.SubnetName
            $size = $null
            if ($col) { $size = $row.$col }
            $node.Resources.Add([ordered]@{ ResourceKey = $row.ResourceKey; ResourceType = $row.ResourceType; ResourceName = $row.ResourceName; NetworkAccess = $row.NetworkAccess; HeadlineSize = $size; HeadlineUnit = $script:SummarySources[$out].Unit })
        }
    }
    return $root
}

function Get-OutputColumns {
    param([string]$Key)
    if ($script:PlainSchemas.Contains($Key)) { return , ([string[]]$script:PlainSchemas[$Key]) }
    $cols = New-List
    foreach ($c in $script:PlacementColumns) { $cols.Add($c) }
    foreach ($c in (Get-TagColumnNames)) { $cols.Add($c) }
    foreach ($c in $script:OutputSchemas[$Key]) { $cols.Add($c) }
    return , $cols.ToArray()
}

function Export-AssessmentFiles {
    param([string]$Path)
    $counts = New-List
    foreach ($k in $script:OutputOrder) {
        $file = Join-Path $Path ($k + '.csv')
        $cols = Get-OutputColumns -Key $k
        $rows = $script:State.Outputs[$k]
        if ($k -eq 'errors') { $rows = $script:State.Errors }
        if ($rows.Count -eq 0) {
            ('"' + ($cols -join '","') + '"') | Set-Content -Path $file -Encoding UTF8 -ErrorAction Stop
        }
        else {
            $rows | Select-Object -Property $cols | Export-Csv -Path $file -NoTypeInformation -Encoding UTF8 -ErrorAction Stop
        }
        $counts.Add([pscustomobject]@{ File = ($k + '.csv'); Rows = $rows.Count })
    }
    return , $counts
}

