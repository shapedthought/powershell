function Get-CosmosApiKind {
    <# Derived from resource type, Kind and Capabilities; never from the name. #>
    param([string]$ResourceType, [string]$Kind, [string[]]$Capabilities)
    $t = ConvertTo-Lower $ResourceType
    if ($t -eq 'microsoft.documentdb/mongoclusters') { return 'MongoDBvCore' }
    if ($t -eq 'microsoft.dbforpostgresql/servergroupsv2') { return 'PostgreSQL' }
    if ($Kind -eq 'MongoDB') { return 'MongoDB' }
    $caps = @($Capabilities | ForEach-Object { ([string]$_).ToLowerInvariant() })
    if ($caps -contains 'enablecassandra') { return 'Cassandra' }
    if ($caps -contains 'enabletable') { return 'Table' }
    if ($caps -contains 'enablegremlin') { return 'Gremlin' }
    if ($caps -contains 'enablemongo') { return 'MongoDB' }
    return 'NoSQL'
}

function Get-CosmosProtectionBlockers {
    param([string]$ApiKind, [string]$BackupPolicyType, [bool]$MultiRegionWrites, [string]$KeyType)
    $b = New-List
    if ($BackupPolicyType -eq 'Periodic') { $b.Add('PeriodicBackup') }
    if ($MultiRegionWrites) { $b.Add('MultiRegionWrites') }
    if ($KeyType -eq 'CustomerManaged') { $b.Add('CustomerManagedKeyRestore') }
    if (@('MongoDBvCore', 'Cassandra') -contains $ApiKind) { $b.Add('UnsupportedApi') }
    return ($b -join ';')
}

function Get-CosmosChildCounts {
    param([string]$ApiKind, [string]$ResourceGroup, [string]$AccountName)
    $result = @{ Databases = $null; Containers = $null }
    switch ($ApiKind) {
        'NoSQL' {
            $dbs = @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBSqlDatabase -ResourceGroupName $ResourceGroup -AccountName $AccountName -ErrorAction Stop })
            $n = 0
            foreach ($d in $dbs) { $dn = [string]$d.Name; $n += @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBSqlContainer -ResourceGroupName $ResourceGroup -AccountName $AccountName -DatabaseName $dn -ErrorAction Stop }).Count }
            $result.Databases = $dbs.Count; $result.Containers = $n
        }
        'MongoDB' {
            $dbs = @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBMongoDBDatabase -ResourceGroupName $ResourceGroup -AccountName $AccountName -ErrorAction Stop })
            $n = 0
            foreach ($d in $dbs) { $dn = [string]$d.Name; $n += @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBMongoDBCollection -ResourceGroupName $ResourceGroup -AccountName $AccountName -DatabaseName $dn -ErrorAction Stop }).Count }
            $result.Databases = $dbs.Count; $result.Containers = $n
        }
        'Gremlin' {
            $dbs = @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBGremlinDatabase -ResourceGroupName $ResourceGroup -AccountName $AccountName -ErrorAction Stop })
            $n = 0
            foreach ($d in $dbs) { $dn = [string]$d.Name; $n += @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBGremlinGraph -ResourceGroupName $ResourceGroup -AccountName $AccountName -DatabaseName $dn -ErrorAction Stop }).Count }
            $result.Databases = $dbs.Count; $result.Containers = $n
        }
        'Table' {
            $result.Containers = @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBTable -ResourceGroupName $ResourceGroup -AccountName $AccountName -ErrorAction Stop }).Count
        }
        'Cassandra' {
            $ks = @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBCassandraKeyspace -ResourceGroupName $ResourceGroup -AccountName $AccountName -ErrorAction Stop })
            $n = 0
            foreach ($k in $ks) { $kn = [string]$k.Name; $n += @(Invoke-WithRetry -ScriptBlock { Get-AzCosmosDBCassandraTable -ResourceGroupName $ResourceGroup -AccountName $AccountName -KeyspaceName $kn -ErrorAction Stop }).Count }
            $result.Databases = $ks.Count; $result.Containers = $n
        }
    }
    return $result
}

function Get-CosmosInventory {
    param($Subscription)
    $subId = [string]$Subscription.Id
    $records = New-List
    $resources = Get-SubscriptionResources -Subscription $Subscription
    $accounts = New-List; $others = New-List
    foreach ($r in $resources) {
        if ((ConvertTo-Lower ([string]$r.ResourceType)) -eq 'microsoft.documentdb/databaseaccounts') { $accounts.Add($r) }
    }
    # mongoClusters and serverGroupsv2 have no dedicated Az cmdlets: read them with
    # Get-AzResource -ResourceType ... -ExpandProperties.
    foreach ($rt in @('Microsoft.DocumentDB/mongoClusters', 'Microsoft.DBforPostgreSQL/serverGroupsv2')) {
        try {
            foreach ($x in @(Invoke-WithRetry -Operation "Get-AzResource $rt" -ScriptBlock { Get-AzResource -ResourceType $rt -ExpandProperties -ErrorAction Stop })) { $others.Add($x) }
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'cosmos' -Operation "Get-AzResource -ResourceType $rt" -Message $_.Exception.Message }
    }
    foreach ($r in $accounts) {
        $rid = [string]$r.ResourceId
        try {
            $rgName = [string]$r.ResourceGroupName
            $accName = [string]$r.Name
            $acct = Invoke-WithRetry -Operation 'Get-AzCosmosDBAccount' -ScriptBlock { Get-AzCosmosDBAccount -ResourceGroupName $rgName -Name $accName -ErrorAction Stop }
            $accId = [string](Get-Prop $acct 'Id')
            if (-not $accId) { $accId = $rid }
            $caps = @(Get-Prop $acct 'Capabilities' | ForEach-Object { [string](Get-Prop $_ 'Name') })
            $kind = [string](Get-Prop $acct 'Kind')
            $api = Get-CosmosApiKind -ResourceType 'Microsoft.DocumentDB/databaseAccounts' -Kind $kind -Capabilities $caps
            $rec = New-WorkloadRecord -Output 'cosmos_accounts' -Module 'cosmos' -ResourceId $accId -Subscription $Subscription -ResourceGroup $rgName `
                -Region (Get-Prop $acct 'Location') -ResourceName $accName -ResourceType 'Microsoft.DocumentDB/databaseAccounts' -Tags (Get-Prop $acct 'Tags') -Candidate $script:CosmosProtection[$api]
            $pna = [string](Get-Prop $acct 'PublicNetworkAccess')
            if (-not $pna) { $pna = 'Enabled' }
            $vnetFilter = [bool](Get-Prop $acct 'IsVirtualNetworkFilterEnabled')
            $ipRules = @(Get-Prop $acct 'IpRules')
            $rec.Net.PeTargetId = $accId
            $rec.Net.PublicNetworkAccess = $pna
            foreach ($v in @(Get-Prop $acct 'VirtualNetworkRules')) { $sid = [string](Get-Prop $v 'Id'); if ($sid) { $rec.Net.VNetRuleSubnetIds.Add($sid) } }
            $rec.Net.IpRuleCount = $ipRules.Count
            if ($vnetFilter -or $ipRules.Count -gt 0) { $rec.Net.DefaultAction = 'Deny' } else { $rec.Net.DefaultAction = 'Allow' }

            $backupType = [string](Get-Prop $acct 'BackupPolicy.BackupType', 'BackupPolicy.Type')
            $multiWrite = [bool](Get-Prop $acct 'EnableMultipleWriteLocations')
            $keyType = 'ServiceManaged'
            if ([string](Get-Prop $acct 'KeyVaultKeyUri')) { $keyType = 'CustomerManaged' }
            $c = $rec.Columns
            $c.ApiKind = $api
            $c.Kind = $kind
            $c.Capabilities = Join-List $caps
            $c.BackupPolicyType = $backupType
            if ($backupType -eq 'Continuous') {
                $c.ContinuousTier = [string](Get-Prop $acct 'BackupPolicy.ContinuousModeTier', 'BackupPolicy.Tier', 'BackupPolicy.ContinuousModeProperties.Tier')
            }
            else {
                $c.PeriodicIntervalMinutes = Get-Prop $acct 'BackupPolicy.BackupIntervalInMinutes'
                $c.PeriodicRetentionHours = Get-Prop $acct 'BackupPolicy.BackupRetentionIntervalInHours'
            }
            $c.BackupStorageRedundancy = [string](Get-Prop $acct 'BackupPolicy.BackupStorageRedundancy')
            $c.WriteRegions = Join-List (@(Get-Prop $acct 'WriteLocations') | ForEach-Object { Format-Region (Get-Prop $_ 'LocationName') })
            $c.ReadRegions = Join-List (@(Get-Prop $acct 'ReadLocations') | ForEach-Object { Format-Region (Get-Prop $_ 'LocationName') })
            $c.MultiRegionWrites = $multiWrite
            $c.KeyType = $keyType
            $c.ProtectionBlockers = Get-CosmosProtectionBlockers -ApiKind $api -BackupPolicyType $backupType -MultiRegionWrites $multiWrite -KeyType $keyType
            $c.RepositoryBackupSupported = (@('PostgreSQL', 'MongoDB') -contains $api)
            $c.PublicNetworkAccess = $pna
            $c.IsVirtualNetworkFilterEnabled = $vnetFilter
            $c.VNetRuleCount = $rec.Net.VNetRuleSubnetIds.Count
            $c.IpRuleCount = $ipRules.Count
            $c.DataUsage_GiB = ConvertTo-GiB (Get-MetricValue -ResourceId $accId -MetricName 'DataUsage' -Module 'cosmos' -SubscriptionId $subId)
            $c.IndexUsage_GiB = ConvertTo-GiB (Get-MetricValue -ResourceId $accId -MetricName 'IndexUsage' -Module 'cosmos' -SubscriptionId $subId)
            try {
                $counts = Get-CosmosChildCounts -ApiKind $api -ResourceGroup $rgName -AccountName $accName
                $c.DatabaseCount = $counts.Databases
                $c.ContainerCount = $counts.Containers
            }
            catch { Add-ErrorRow -SubscriptionId $subId -Module 'cosmos' -ResourceKey $accId -Operation 'CosmosChildCounts' -Message $_.Exception.Message }
            $records.Add($rec)
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'cosmos' -ResourceKey $rid -Operation 'BuildCosmosRow' -Message $_.Exception.Message }
    }
    foreach ($r in $others) {
        $rid = [string]$r.ResourceId
        try {
            $full = $r
            $api = Get-CosmosApiKind -ResourceType ([string]$r.ResourceType) -Kind '' -Capabilities @()
            $rec = New-WorkloadRecord -Output 'cosmos_accounts' -Module 'cosmos' -ResourceId $rid -Subscription $Subscription -ResourceGroup $r.ResourceGroupName `
                -Region $r.Location -ResourceName $r.Name -ResourceType ([string]$r.ResourceType) -Tags (Get-Prop $r 'Tags') -Candidate $script:CosmosProtection[$api]
            $pna = [string](Get-Prop $full 'Properties.publicNetworkAccess')
            if (-not $pna) { $pna = 'Enabled' }
            $rec.Net.PeTargetId = $rid
            $rec.Net.PublicNetworkAccess = $pna
            $c = $rec.Columns
            $c.ApiKind = $api
            $c.Kind = [string](Get-Prop $full 'Kind')
            $keyType = 'ServiceManaged'
            if (Get-Prop $full 'Properties.encryption.customerManagedKeyEncryption', 'Properties.dataEncryption.primaryKeyUri') { $keyType = 'CustomerManaged' }
            $c.KeyType = $keyType
            # Protection blockers apply to Microsoft.DocumentDB/databaseAccounts only.
            $c.ProtectionBlockers = ''
            $c.RepositoryBackupSupported = (@('PostgreSQL', 'MongoDB') -contains $api)
            $c.PublicNetworkAccess = $pna
            $records.Add($rec)
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'cosmos' -ResourceKey $rid -Operation 'BuildCosmosRow' -Message $_.Exception.Message }
    }
    Write-Step ("    {0} Cosmos DB account(s), {1} vCore/PostgreSQL cluster(s)" -f $accounts.Count, $others.Count)
    return , $records
}

function Get-FileShareInventory {
    param($Subscription)
    $subId = [string]$Subscription.Id
    $records = New-List
    $accounts = Get-SubscriptionStorageAccounts -Subscription $Subscription
    $shareTotal = 0
    foreach ($sa in $accounts) {
        $kind = [string](Get-Prop $sa 'Kind')
        if (@('StorageV2', 'Storage', 'FileStorage') -notcontains $kind) { continue }
        $rg = [string]$sa.ResourceGroupName
        $san = [string]$sa.StorageAccountName
        try {
            # Hidden parent record for the storage account (not exported): shares inherit from it even
            # when the blob module is not selected.
            $parent = New-WorkloadRecord -Output '' -Module 'files' -ResourceId $sa.Id -Subscription $Subscription -ResourceGroup $rg `
                -Region (Get-Prop $sa 'PrimaryLocation', 'Location') -ResourceName $san -ResourceType 'Microsoft.Storage/storageAccounts' -Tags (Get-Prop $sa 'Tags') -Candidate $script:WorkloadMap.files
            Set-StorageAccountNetwork -Record $parent -StorageAccount $sa -GroupFilter $null
            $records.Add($parent)
            $softDeleteEnabled = $null; $softDeleteDays = $null
            try {
                $fsp = Invoke-WithRetry -Operation 'Get-AzStorageFileServiceProperty' -ScriptBlock { Get-AzStorageFileServiceProperty -ResourceGroupName $rg -StorageAccountName $san -ErrorAction Stop }
                $softDeleteEnabled = Get-Prop $fsp 'ShareDeleteRetentionPolicy.Enabled'
                $softDeleteDays = Get-Prop $fsp 'ShareDeleteRetentionPolicy.Days'
            }
            catch { Add-ErrorRow -SubscriptionId $subId -Module 'files' -ResourceKey $sa.Id -Operation 'Get-AzStorageFileServiceProperty' -Message $_.Exception.Message }
            $all = @(Invoke-WithRetry -Operation 'Get-AzRmStorageShare' -ScriptBlock { Get-AzRmStorageShare -ResourceGroupName $rg -StorageAccountName $san -IncludeSnapshot -ErrorAction Stop })
            $snapCount = @{}
            $bases = New-List
            foreach ($s in $all) {
                if (Get-Prop $s 'SnapshotTime') {
                    $k = ([string]$s.Name).ToLowerInvariant()
                    if ($snapCount.ContainsKey($k)) { $snapCount[$k]++ } else { $snapCount[$k] = 1 }
                }
                elseif (-not (Get-Prop $s 'Deleted')) { $bases.Add($s) }
            }
            foreach ($s in $bases) {
                $shareName = [string]$s.Name
                $shareId = [string](Get-Prop $s 'Id')
                if (-not $shareId) { $shareId = [string]$sa.Id + '/fileServices/default/shares/' + $shareName }
                $rec = New-WorkloadRecord -Output 'file_shares' -Module 'files' -ResourceId $shareId -Subscription $Subscription -ResourceGroup $rg `
                    -Region (Get-Prop $sa 'PrimaryLocation', 'Location') -ResourceName "$san/$shareName" -ResourceType 'Microsoft.Storage/storageAccounts/fileServices/shares' -Tags (Get-Prop $sa 'Tags') -Candidate $script:WorkloadMap.files
                # Storage private endpoints are per service: a share is reachable only through
                # 'file' endpoints, so it is placed on those rather than inheriting the account row.
                Set-StorageAccountNetwork -Record $rec -StorageAccount $sa -GroupFilter @('file')
                $c = $rec.Columns
                $c.StorageAccountName = $san
                $c.ShareName = $shareName
                $proto = [string](Get-Prop $s 'EnabledProtocols')
                if (-not $proto) { $proto = 'SMB' }
                $c.Protocol = $proto
                $c.Quota_GiB = Get-Prop $s 'QuotaGiB'
                try {
                    $u = Invoke-WithRetry -Operation 'Get-AzRmStorageShare -GetShareUsage' -ScriptBlock { Get-AzRmStorageShare -ResourceGroupName $rg -StorageAccountName $san -Name $shareName -GetShareUsage -ErrorAction Stop }
                    $c.Used_GiB = ConvertTo-GiB (Get-Prop $u 'ShareUsageBytes')
                }
                catch { Add-ErrorRow -SubscriptionId $subId -Module 'files' -ResourceKey $shareId -Operation 'Get-AzRmStorageShare -GetShareUsage' -Message $_.Exception.Message }
                $c.AccessTier = [string](Get-Prop $s 'AccessTier')
                $c.ShareSoftDeleteEnabled = $softDeleteEnabled
                $c.ShareSoftDeleteDays = $softDeleteDays
                $sc = 0
                if ($snapCount.ContainsKey($shareName.ToLowerInvariant())) { $sc = $snapCount[$shareName.ToLowerInvariant()] }
                $c.SnapshotCount = $sc
                $c.StorageAccountKind = $kind
                $c.StorageAccountSku = [string](Get-Prop $sa 'Sku.Name')
                $c.LargeFileShares = [string](Get-Prop $sa 'LargeFileSharesState')
                $c.IdentityBasedAuth = [string](Get-Prop $sa 'AzureFilesIdentityBasedAuth.DirectoryServiceOptions')
                $records.Add($rec)
                $shareTotal++
            }
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'files' -ResourceKey $sa.Id -Operation 'Get-AzRmStorageShare' -Message $_.Exception.Message }
    }
    Write-Step ("    {0} file share(s)" -f $shareTotal)
    return , $records
}

function Get-StorageLikelyPurpose {
    <# HEURISTIC ONLY: infers purpose from tags and well-known account/container name patterns. It can
       be wrong; verify before using it for design decisions. #>
    param([string]$Name, $Tags, [string[]]$ContainerNames)
    foreach ($t in (Get-TagPairs $Tags)) {
        if ($t.Key -eq 'ms-resource-usage' -and $t.Value -eq 'azure-cloud-shell') { return 'CloudShell' }
        if ($t.Key -match '(?i)veeam' -or $t.Value -match '(?i)veeam') { return 'VeeamRepository' }
    }
    if ($Name -match '(?i)veeam') { return 'VeeamRepository' }
    foreach ($cn in $ContainerNames) { if ($cn -match '(?i)veeam') { return 'VeeamRepository' } }
    foreach ($cn in $ContainerNames) { if ($cn -match '^(?i)bootdiagnostics-') { return 'BootDiagnostics' } }
    if ($Name -match '(?i)bootdiag') { return 'BootDiagnostics' }
    if ($Name -match '^(?i)cs[0-9a-f]{6,}') { return 'CloudShell' }
    return 'Other'
}

function Get-StorageAccountInventory {
    param($Subscription)
    $subId = [string]$Subscription.Id
    $records = New-List
    $accounts = Get-SubscriptionStorageAccounts -Subscription $Subscription
    foreach ($sa in $accounts) {
        $saId = [string]$sa.Id
        try {
            $rg = [string]$sa.ResourceGroupName
            $san = [string]$sa.StorageAccountName
            $kind = [string](Get-Prop $sa 'Kind')
            # A FileStorage account has no blob service: its row is the Azure Files workload, placed on
            # 'file' endpoints. Every other kind is the Blob workload, placed on 'blob' / 'dfs' endpoints.
            $candidate = $script:WorkloadMap.blob; $groupFilter = @('blob', 'dfs')
            if ($kind -eq 'FileStorage') { $candidate = $script:WorkloadMap.files; $groupFilter = @('file') }
            $rec = New-WorkloadRecord -Output 'storage_accounts' -Module 'blob' -ResourceId $saId -Subscription $Subscription -ResourceGroup $rg `
                -Region (Get-Prop $sa 'PrimaryLocation', 'Location') -ResourceName $san -ResourceType 'Microsoft.Storage/storageAccounts' -Tags (Get-Prop $sa 'Tags') -Candidate $candidate
            Set-StorageAccountNetwork -Record $rec -StorageAccount $sa -GroupFilter $groupFilter
            $hasBlob = ($kind -ne 'FileStorage')
            $hasFile = (@('StorageV2', 'Storage', 'FileStorage') -contains $kind)
            $c = $rec.Columns
            $containerNames = @()
            $containerImmutability = $false
            if ($hasBlob) {
                try {
                    $bsp = Invoke-WithRetry -Operation 'Get-AzStorageBlobServiceProperty' -ScriptBlock { Get-AzStorageBlobServiceProperty -ResourceGroupName $rg -StorageAccountName $san -ErrorAction Stop }
                    $c.VersioningEnabled = Get-Prop $bsp 'IsVersioningEnabled'
                    if (Get-Prop $bsp 'DeleteRetentionPolicy.Enabled') { $c.BlobSoftDeleteDays = Get-Prop $bsp 'DeleteRetentionPolicy.Days' } else { $c.BlobSoftDeleteDays = 0 }
                    if (Get-Prop $bsp 'ContainerDeleteRetentionPolicy.Enabled') { $c.ContainerSoftDeleteDays = Get-Prop $bsp 'ContainerDeleteRetentionPolicy.Days' } else { $c.ContainerSoftDeleteDays = 0 }
                    $c.ChangeFeedEnabled = [bool](Get-Prop $bsp 'ChangeFeed.Enabled')
                    $c.PointInTimeRestoreEnabled = [bool](Get-Prop $bsp 'RestorePolicy.Enabled')
                    $c.PointInTimeRestoreDays = Get-Prop $bsp 'RestorePolicy.Days'
                }
                catch { Add-ErrorRow -SubscriptionId $subId -Module 'blob' -ResourceKey $saId -Operation 'Get-AzStorageBlobServiceProperty' -Message $_.Exception.Message }
                try {
                    # ARM (management-plane) container listing: names/flags only, never blob contents.
                    $containers = @(Invoke-WithRetry -Operation 'Get-AzRmStorageContainer' -ScriptBlock { Get-AzRmStorageContainer -ResourceGroupName $rg -StorageAccountName $san -ErrorAction Stop })
                    $containerNames = @($containers | ForEach-Object { [string]$_.Name })
                    $c.ContainerCount = $containers.Count
                    foreach ($ct in $containers) { if ((Get-Prop $ct 'HasImmutabilityPolicy') -eq $true -or (Get-Prop $ct 'HasLegalHold') -eq $true) { $containerImmutability = $true } }
                }
                catch { Add-ErrorRow -SubscriptionId $subId -Module 'blob' -ResourceKey $saId -Operation 'Get-AzRmStorageContainer' -Message $_.Exception.Message }
            }
            $c.Kind = $kind
            $c.Sku = [string](Get-Prop $sa 'Sku.Name')
            $c.AccessTier = [string](Get-Prop $sa 'AccessTier')
            $c.HnsEnabled = [bool](Get-Prop $sa 'EnableHierarchicalNamespace')
            $c.UsedCapacity_GiB = ConvertTo-GiB (Get-MetricValue -ResourceId $saId -MetricName 'UsedCapacity' -Module 'blob' -SubscriptionId $subId)
            if ($hasBlob) {
                $blobSvc = $saId + '/blobServices/default'
                $c.BlobCapacity_GiB = ConvertTo-GiB (Get-MetricValue -ResourceId $blobSvc -MetricName 'BlobCapacity' -Module 'blob' -SubscriptionId $subId -ResourceKey $saId)
            }
            else { $c.ContainerCount = 0 }
            if ($hasFile) {
                $fileSvc = $saId + '/fileServices/default'
                $c.FileCapacity_GiB = ConvertTo-GiB (Get-MetricValue -ResourceId $fileSvc -MetricName 'FileCapacity' -Module 'blob' -SubscriptionId $subId -ResourceKey $saId)
                try {
                    # Counted from the ARM share listing (snapshots and soft-deleted shares excluded).
                    $shares = @(Invoke-WithRetry -Operation 'Get-AzRmStorageShare' -ScriptBlock { Get-AzRmStorageShare -ResourceGroupName $rg -StorageAccountName $san -ErrorAction Stop })
                    $n = 0
                    foreach ($sh in $shares) { if (-not (Get-Prop $sh 'SnapshotTime') -and -not (Get-Prop $sh 'Deleted')) { $n++ } }
                    $c.FileShareCount = $n
                }
                catch { Add-ErrorRow -SubscriptionId $subId -Module 'blob' -ResourceKey $saId -Operation 'Get-AzRmStorageShare' -Message $_.Exception.Message }
            }
            else { $c.FileShareCount = 0 }
            $accountImmutable = [bool](Get-Prop $sa 'ImmutableStorageWithVersioning.Enabled')
            if ($accountImmutable) { $c.Immutability = 'AccountVersionLevel' }
            elseif ($containerImmutability) { $c.Immutability = 'ContainerPolicyOrLegalHold' }
            else { $c.Immutability = 'None' }
            $c.SftpEnabled = [bool](Get-Prop $sa 'EnableSftp')
            $c.NfsV3Enabled = [bool](Get-Prop $sa 'EnableNfsV3')
            $sk = Get-Prop $sa 'AllowSharedKeyAccess'
            if ($null -eq $sk) { $c.AllowSharedKeyAccess = $true } else { $c.AllowSharedKeyAccess = [bool]$sk }
            $c.MinimumTlsVersion = [string](Get-Prop $sa 'MinimumTlsVersion')
            $c.PublicNetworkAccess = $rec.Net.PublicNetworkAccess
            $c.DefaultNetworkAction = $rec.Net.DefaultAction
            $c.IpRuleCount = $rec.Net.IpRuleCount
            $c.VNetRuleCount = $rec.Net.VNetRuleSubnetIds.Count
            $c.LikelyPurpose = Get-StorageLikelyPurpose -Name $san -Tags (Get-Prop $sa 'Tags') -ContainerNames $containerNames
            $records.Add($rec)
        }
        catch { Add-ErrorRow -SubscriptionId $subId -Module 'blob' -ResourceKey $saId -Operation 'BuildStorageAccountRow' -Message $_.Exception.Message }
    }
    Write-Step ("    {0} storage account(s)" -f @($accounts).Count)
    return , $records
}

