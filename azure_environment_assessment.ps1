function Get-BackupInventory {
    <# Existing native protection (-BackupAssessment). Vault rows carry the vault's own placement. #>
    param($Subscription, [bool]$RecoveryServices = $true, [bool]$DataProtection = $true)
    $subId = [string]$Subscription.Id
    $records = New-List
    $vaultCandidate = ''
    if ($RecoveryServices) {
        $vaults = @()
        try { $vaults = @(Invoke-WithRetry -Operation 'Get-AzRecoveryServicesVault' -ScriptBlock { Get-AzRecoveryServicesVault -ErrorAction Stop }) }
        catch { Set-CoverageIncomplete $subId; Add-ErrorRow -SubscriptionId $subId -Module 'backup' -Operation 'Get-AzRecoveryServicesVault' -Message $_.Exception.Message }
        foreach ($v in $vaults) {
            $vid = [string](Get-Prop $v 'ID', 'Id')
            $vname = [string]$v.Name
            try {
                $newVaultRecord = {
                    # Vault child rows (items, policies) carry their own ResourceKey/ResourceName/type and
                    # inherit the vault's placement; job rows keep the vault's identity.
                    param([string]$Output, [string]$ChildId, [string]$ChildName, [string]$ChildType)
                    $cid = $vid; $cname = $vname; $ctype = 'Microsoft.RecoveryServices/vaults'
                    if ($ChildId) { $cid = $ChildId; $cname = $ChildName; $ctype = $ChildType }
                    $r = New-WorkloadRecord -Output $Output -Module 'backup' -ResourceId $cid -Subscription $Subscription -ResourceGroup $v.ResourceGroupName `
                        -Region $v.Location -ResourceName $cname -ResourceType $ctype -Tags (Get-Prop $v 'Tags') -Candidate $vaultCandidate
                    $r.Net.InheritFrom = $vid
                    if ($r.Columns.Contains('VaultType')) { $r.Columns.VaultType = 'RecoveryServicesVault' }
                    if ($r.Columns.Contains('VaultName')) { $r.Columns.VaultName = $vname }
                    $r
                }
                $vrec = New-WorkloadRecord -Output 'backup_vaults' -Module 'backup' -ResourceId $vid -Subscription $Subscription -ResourceGroup $v.ResourceGroupName `
                    -Region $v.Location -ResourceName $vname -ResourceType 'Microsoft.RecoveryServices/vaults' -Tags (Get-Prop $v 'Tags') -Candidate $vaultCandidate
                $vrec.Net.PeTargetId = $vid
                $pna = [string](Get-Prop $v 'Properties.PublicNetworkAccess')
                if (-not $pna) { $pna = 'Enabled' }
                $vrec.Net.PublicNetworkAccess = $pna
                $vrec.Columns.VaultType = 'RecoveryServicesVault'
                $itemCount = 0
                foreach ($combo in @(@('AzureIaasVM', 'AzureVM'), @('AzureStorage', 'AzureFiles'), @('AzureWorkload', 'MSSQL'), @('AzureWorkload', 'SAPHanaDatabase'))) {
                    $bmt = $combo[0]; $wt = $combo[1]
                    try {
                        $items = @(Invoke-WithRetry -Operation "Get-AzRecoveryServicesBackupItem $wt" -ScriptBlock { Get-AzRecoveryServicesBackupItem -BackupManagementType $bmt -WorkloadType $wt -VaultId $vid -ErrorAction Stop })
                    }
                    catch { Set-CoverageIncomplete $subId; Add-ErrorRow -SubscriptionId $subId -Module 'backup' -ResourceKey $vid -Operation "Get-AzRecoveryServicesBackupItem $wt" -Message $_.Exception.Message; continue }
                    foreach ($it in $items) {
                        $itemCount++
                        $src = [string](Get-Prop $it 'SourceResourceId')
                        $protKey = $src
                        $protName = Get-NameFromId $src
                        if ($wt -eq 'AzureFiles') {
                            $share = [string](Get-Prop $it 'FriendlyName')
                            if ($src -and $share) { $protKey = $src + '/fileServices/default/shares/' + $share; $protName = (Get-NameFromId $src) + '/' + $share }
                        }
                        $policy = [string](Get-Prop $it 'ProtectionPolicyName')
                        if ($protKey -and ($wt -eq 'AzureVM' -or $wt -eq 'AzureFiles')) {
                            $ck = ConvertTo-Lower $protKey
                            Add-CoverageEntry -Key $ck -NativeBackup 'RecoveryServicesVault' -VaultName $vname -PolicyName $policy -ProtectionState ([string](Get-Prop $it 'ProtectionState'))
                        }
                        $itemName = [string](Get-Prop $it 'Name')
                        $itemId = [string](Get-Prop $it 'Id')
                        if (-not $itemId) { $itemId = $vid + '/backupItems/' + $itemName }
                        $irec = & $newVaultRecord 'backup_items' $itemId $itemName 'Microsoft.RecoveryServices/vaults/backupFabrics/protectionContainers/protectedItems'
                        $ic = $irec.Columns
                        $ic.ItemName = [string](Get-Prop $it 'Name')
                        $ic.WorkloadType = $wt
                        $ic.ProtectedResourceKey = ConvertTo-Lower $protKey
                        $ic.ProtectedResourceName = $protName
                        $ic.PolicyName = $policy
                        $ic.ProtectionState = [string](Get-Prop $it 'ProtectionState')
                        $ic.LastBackupStatus = [string](Get-Prop $it 'LastBackupStatus')
                        $lrp = Get-Prop $it 'LatestRecoveryPoint'
                        if ($lrp) { $ic.LatestRecoveryPoint = ([datetime]$lrp).ToUniversalTime().ToString('o') }
                        $records.Add($irec)
                    }
                }
                $vrec.Columns.ItemCount = $itemCount
                $policies = @()
                try { $policies = @(Invoke-WithRetry -Operation 'Get-AzRecoveryServicesBackupProtectionPolicy' -ScriptBlock { Get-AzRecoveryServicesBackupProtectionPolicy -VaultId $vid -ErrorAction Stop }) }
                catch { Add-ErrorRow -SubscriptionId $subId -Module 'backup' -ResourceKey $vid -Operation 'Get-AzRecoveryServicesBackupProtectionPolicy' -Message $_.Exception.Message }
                foreach ($p in $policies) {
                    $polId = [string](Get-Prop $p 'Id')
                    if (-not $polId) { $polId = $vid + '/backupPolicies/' + [string]$p.Name }
                    $prec = & $newVaultRecord 'backup_policies' $polId ([string]$p.Name) 'Microsoft.RecoveryServices/vaults/backupPolicies'
                    $pc = $prec.Columns
                    $pc.PolicyName = [string]$p.Name
                    $pc.WorkloadType = [string](Get-Prop $p 'WorkloadType')
                    $sp = Get-Prop $p 'SchedulePolicy', 'FullBackupSchedulePolicy'
                    $freq = [string](Get-Prop $sp 'ScheduleRunFrequency')
                    $times = Join-List (@(Get-Prop $sp 'ScheduleRunTimes') | ForEach-Object { ([datetime]$_).ToString('HH:mm') }) ','
                    $pc.Schedule = (($freq + ' ' + $times).Trim())
                    $rp = Get-Prop $p 'RetentionPolicy', 'FullBackupRetentionPolicy'
                    $ret = New-List
                    foreach ($pair in @(@('D', 'Daily', 'DurationCountInDays'), @('W', 'Weekly', 'DurationCountInWeeks'), @('M', 'Monthly', 'DurationCountInMonths'), @('Y', 'Yearly', 'DurationCountInYears'))) {
                        $sched = $pair[1] + 'Schedule'
                        $val = Get-Prop $rp ($sched + '.' + $pair[2])
                        if ($null -eq $val) { continue }
                        # Respect disabled schedules (Is<X>ScheduleEnabled = false); absent flag = enabled.
                        $enabledFlag = Get-Prop $rp ('Is' + $pair[1] + 'ScheduleEnabled')
                        if ($null -ne $enabledFlag -and -not [bool]$enabledFlag) { continue }
                        $ret.Add($pair[0] + ':' + $val)
                    }
                    $pc.Retention = $ret -join ';'
                    $records.Add($prec)
                }
                $vrec.Columns.PolicyCount = $policies.Count
                try {
                    $to = (Get-Date).ToUniversalTime()
                    $from = $to.AddDays(-7)
                    $jobs = @(Invoke-WithRetry -Operation 'Get-AzRecoveryServicesBackupJob' -ScriptBlock { Get-AzRecoveryServicesBackupJob -VaultId $vid -From $from -To $to -ErrorAction Stop })
                    foreach ($j in $jobs) {
                        $jrec = & $newVaultRecord 'backup_jobs'
                        $jc = $jrec.Columns
                        $jc.JobId = [string](Get-Prop $j 'JobId')
                        $jc.Operation = [string](Get-Prop $j 'Operation')
                        $jc.Status = [string](Get-Prop $j 'Status')
                        $jc.WorkloadName = [string](Get-Prop $j 'WorkloadName')
                        $st = Get-Prop $j 'StartTime'; if ($st) { $jc.StartTime = ([datetime]$st).ToUniversalTime().ToString('o') }
                        $et = Get-Prop $j 'EndTime'; if ($et) { $jc.EndTime = ([datetime]$et).ToUniversalTime().ToString('o') }
                        $du = Get-Prop $j 'Duration'; if ($du) { $jc.DurationMinutes = [math]::Round(([timespan]$du).TotalMinutes, 1) }
                        $records.Add($jrec)
                    }
                }
                catch { Add-ErrorRow -SubscriptionId $subId -Module 'backup' -ResourceKey $vid -Operation 'Get-AzRecoveryServicesBackupJob' -Message $_.Exception.Message }
                $records.Add($vrec)
            }
            catch { Set-CoverageIncomplete $subId; Add-ErrorRow -SubscriptionId $subId -Module 'backup' -ResourceKey $vid -Operation 'ProcessRecoveryServicesVault' -Message $_.Exception.Message }
        }
    }
    if ($DataProtection) {
        $bvs = @()
        try { $bvs = @(Invoke-WithRetry -Operation 'Get-AzDataProtectionBackupVault' -ScriptBlock { Get-AzDataProtectionBackupVault -SubscriptionId $subId -ErrorAction Stop }) }
        catch { Set-CoverageIncomplete $subId; Add-ErrorRow -SubscriptionId $subId -Module 'backup' -Operation 'Get-AzDataProtectionBackupVault' -Message $_.Exception.Message }
        foreach ($bv in $bvs) {
            $bid = [string]$bv.Id
            $bname = [string]$bv.Name
            $brg = (ConvertFrom-ResourceId $bid).ResourceGroup
            try {
                $vrec = New-WorkloadRecord -Output 'backup_vaults' -Module 'backup' -ResourceId $bid -Subscription $Subscription -ResourceGroup $brg `
                    -Region $bv.Location -ResourceName $bname -ResourceType 'Microsoft.DataProtection/backupVaults' -Tags (Get-Prop $bv 'Tag', 'Tags') -Candidate $vaultCandidate
                $vrec.Net.PeTargetId = $bid
                $pna = [string](Get-Prop $bv 'PublicNetworkAccess', 'Property.PublicNetworkAccess')
                if (-not $pna) { $pna = 'Enabled' }
                $vrec.Net.PublicNetworkAccess = $pna
                $vrec.Columns.VaultType = 'BackupVault'
                $policies = @()
                try { $policies = @(Invoke-WithRetry -Operation 'Get-AzDataProtectionBackupPolicy' -ScriptBlock { Get-AzDataProtectionBackupPolicy -ResourceGroupName $brg -VaultName $bname -ErrorAction Stop }) }
                catch { Add-ErrorRow -SubscriptionId $subId -Module 'backup' -ResourceKey $bid -Operation 'Get-AzDataProtectionBackupPolicy' -Message $_.Exception.Message }
                foreach ($p in $policies) {
                    $polId = [string](Get-Prop $p 'Id')
                    if (-not $polId) { $polId = $bid + '/backupPolicies/' + [string]$p.Name }
                    $prec = New-WorkloadRecord -Output 'backup_policies' -Module 'backup' -ResourceId $polId -Subscription $Subscription -ResourceGroup $brg `
                        -Region $bv.Location -ResourceName ([string]$p.Name) -ResourceType 'Microsoft.DataProtection/backupVaults/backupPolicies' -Tags (Get-Prop $bv 'Tag', 'Tags') -Candidate $vaultCandidate
                    $prec.Net.InheritFrom = $bid
                    $pc = $prec.Columns
                    $pc.VaultType = 'BackupVault'; $pc.VaultName = $bname
                    $pc.PolicyName = [string]$p.Name
                    $pc.WorkloadType = Join-List (Get-Prop $p 'Property.DatasourceType')
                    $rules = @(Get-Prop $p 'Property.PolicyRule')
                    $pc.Schedule = Join-List (@($rules | ForEach-Object { Get-Prop $_ 'Trigger.ScheduleRepeatingTimeInterval' }))
                    $pc.Retention = Join-List (@($rules | ForEach-Object { $rn = [string](Get-Prop $_ 'Name'); foreach ($l in @(Get-Prop $_ 'Lifecycle')) { $rn + ':' + [string](Get-Prop $l 'DeleteAfterDuration') } }))
                    $records.Add($prec)
                }
                $instances = @()
                try { $instances = @(Invoke-WithRetry -Operation 'Get-AzDataProtectionBackupInstance' -ScriptBlock { Get-AzDataProtectionBackupInstance -ResourceGroupName $brg -VaultName $bname -ErrorAction Stop }) }
                catch { Set-CoverageIncomplete $subId; Add-ErrorRow -SubscriptionId $subId -Module 'backup' -ResourceKey $bid -Operation 'Get-AzDataProtectionBackupInstance' -Message $_.Exception.Message }
                foreach ($bi in $instances) {
                    $src = [string](Get-Prop $bi 'Property.DataSourceInfo.ResourceId')
                    $policyName = Get-NameFromId ([string](Get-Prop $bi 'Property.PolicyInfo.PolicyId'))
                    if ($src) {
                        $ck = ConvertTo-Lower $src
                        Add-CoverageEntry -Key $ck -NativeBackup 'BackupVault' -VaultName $bname -PolicyName $policyName -ProtectionState ([string](Get-Prop $bi 'Property.CurrentProtectionState'))
                    }
                    $biId = [string](Get-Prop $bi 'Id')
                    if (-not $biId) { $biId = $bid + '/backupInstances/' + [string]$bi.Name }
                    $irec = New-WorkloadRecord -Output 'backup_items' -Module 'backup' -ResourceId $biId -Subscription $Subscription -ResourceGroup $brg `
                        -Region $bv.Location -ResourceName ([string]$bi.Name) -ResourceType 'Microsoft.DataProtection/backupVaults/backupInstances' -Tags (Get-Prop $bv 'Tag', 'Tags') -Candidate $vaultCandidate
                    $irec.Net.InheritFrom = $bid
                    $ic = $irec.Columns
                    $ic.VaultType = 'BackupVault'; $ic.VaultName = $bname
                    $ic.ItemName = [string]$bi.Name
                    $ic.WorkloadType = [string](Get-Prop $bi 'Property.DataSourceInfo.DatasourceType')
                    $ic.ProtectedResourceKey = ConvertTo-Lower $src
                    $ic.ProtectedResourceName = Get-NameFromId $src
                    $ic.PolicyName = $policyName
                    $ic.ProtectionState = [string](Get-Prop $bi 'Property.CurrentProtectionState')
                    $ic.LastBackupStatus = [string](Get-Prop $bi 'Property.ProtectionStatus.Status')
                    $records.Add($irec)
                }
                $vrec.Columns.ItemCount = $instances.Count
                $vrec.Columns.PolicyCount = $policies.Count
                $records.Add($vrec)
            }
            catch { Set-CoverageIncomplete $subId; Add-ErrorRow -SubscriptionId $subId -Module 'backup' -ResourceKey $bid -Operation 'ProcessBackupVault' -Message $_.Exception.Message }
        }
    }
    return , $records
}

