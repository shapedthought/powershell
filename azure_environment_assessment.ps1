function New-List {
    return , (New-Object System.Collections.Generic.List[object])
}

function Get-Prop {
    <# Null-safe nested property read. Accepts several alternative dotted paths; returns the first
       non-null value (enumerated, so wrap the call in @() for collections). Emits nothing if none. #>
    param($Object, [string[]]$Path)
    foreach ($p in $Path) {
        $cur = $Object
        $found = $true
        foreach ($seg in $p.Split('.')) {
            if ($null -eq $cur) { $found = $false; break }
            if ($cur -is [System.Collections.IDictionary]) {
                $hit = $false
                foreach ($k in $cur.Keys) { if ([string]$k -eq $seg) { $cur = $cur[$k]; $hit = $true; break } }
                if (-not $hit) { $found = $false; break }
            }
            else {
                $prop = $cur.PSObject.Properties[$seg]
                if ($null -eq $prop) { $found = $false; break }
                $cur = $prop.Value
            }
        }
        if ($found -and $null -ne $cur) { return $cur }
    }
}

function Get-Count {
    param($Value)
    if ($null -eq $Value) { return 0 }
    if ($Value -is [string]) { return 1 }
    if ($Value -is [System.Collections.ICollection]) { return $Value.Count }
    $n = 0
    foreach ($v in $Value) { $n++ }
    return $n
}

function Join-List {
    param($Value, [string]$Separator = ';')
    if ($null -eq $Value) { return '' }
    $items = New-List
    # foreach (not @()) so generic List[object] values work on every PowerShell version.
    foreach ($v in $Value) { if ($null -ne $v -and [string]$v -ne '') { $items.Add([string]$v) } }
    return ($items -join $Separator)
}

