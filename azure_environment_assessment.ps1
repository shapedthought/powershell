function Resolve-SubnetInfo {
    param([string]$SubnetId, $Record)
    if (-not $SubnetId) { return $null }
    $s = $script:State.Subnets[(ConvertTo-Lower $SubnetId)]
    if ($s) {
        return @{ VNetSubscriptionId = $s.VNetSubscriptionId; VNetResourceGroup = $s.VNetResourceGroup; VNetName = $s.VNetName; SubnetName = $s.Name; SubnetPrefix = ($s.Prefixes -join ';') }
    }
    # Not in the collected backbone (for example the vNet's subscription was unreadable): use the
    # subnet's own ID, parsed by key, and record the gap.
    $p = ConvertFrom-ResourceId $SubnetId
    $vnetName = ''; $subnetName = ''
    if ($p.Segments.ContainsKey('virtualnetworks')) { $vnetName = $p.Segments['virtualnetworks'] }
    if ($p.Segments.ContainsKey('subnets')) { $subnetName = $p.Segments['subnets'] }
    Add-ErrorRow -SubscriptionId $Record.SubscriptionId -Module $Record.Module -ResourceKey $Record.ResourceId -Operation 'ResolveSubnet' `
        -Message "Subnet $SubnetId is not in the collected network backbone (subscription not readable or not selected); prefix left blank."
    return @{ VNetSubscriptionId = $p.SubscriptionId; VNetResourceGroup = $p.ResourceGroup; VNetName = $vnetName; SubnetName = $subnetName; SubnetPrefix = '' }
}

function New-AttachmentRow {
    param([string]$ResourceKey, [string]$Type, [bool]$IsPrimary, $SubnetInfo, [string]$PrivateIp, [string]$PeName, [string]$GroupId)
    $a = [ordered]@{
        ResourceKey = $ResourceKey; AttachmentType = $Type; IsPrimary = $IsPrimary
        VNetSubscriptionId = ''; VNetResourceGroup = ''; VNetName = ''; SubnetName = ''; SubnetPrefix = ''
        PrivateIpAddress = $PrivateIp; PrivateEndpointName = $PeName; GroupId = $GroupId
    }
    if ($SubnetInfo) {
        $a.VNetSubscriptionId = $SubnetInfo.VNetSubscriptionId; $a.VNetResourceGroup = $SubnetInfo.VNetResourceGroup
        $a.VNetName = $SubnetInfo.VNetName; $a.SubnetName = $SubnetInfo.SubnetName; $a.SubnetPrefix = $SubnetInfo.SubnetPrefix
    }
    return $a
}

function Get-PlacementColumns {
    <# Resolves a record's placement against the backbone of ALL subscriptions (hashtable lookups only).
       Returns @{ Placement = [ordered]; Attachments = List }. #>
    param($Record)
    $key = ConvertTo-Lower $Record.ResourceId
    $pl = [ordered]@{
        ResourceKey = $key; TenantId = $Record.TenantId; SubscriptionId = $Record.SubscriptionId; SubscriptionName = $Record.SubscriptionName
        ResourceGroup = $Record.ResourceGroup; Region = $Record.Region; Zones = $Record.Zones; ResourceName = $Record.ResourceName
        ResourceType = $Record.ResourceType; NetworkAccess = ''; VNetSubscriptionId = ''; VNetResourceGroup = ''; VNetName = ''
        SubnetName = ''; SubnetPrefix = ''; PrivateEndpointCount = 0; CandidateVeeamProtection = $Record.Candidate
    }
    $att = New-List
    $net = $Record.Net

    if ($net.InheritFrom) {
        # Child row: keeps its own identity and location (tenant, subscription, resource group,
        # region, zones -- a disk can live in a different resource group from its VM) and inherits
        # only the parent's network placement.
        $parent = $script:State.Resolved[(ConvertTo-Lower $net.InheritFrom)]
        if ($parent) {
            foreach ($f in @('NetworkAccess', 'VNetSubscriptionId', 'VNetResourceGroup', 'VNetName', 'SubnetName', 'SubnetPrefix', 'PrivateEndpointCount')) {
                $pl[$f] = $parent[$f]
            }
        }
        else {
            Add-ErrorRow -SubscriptionId $Record.SubscriptionId -Module $Record.Module -ResourceKey $Record.ResourceId -Operation 'ResolveParent' `
                -Message "Parent $($net.InheritFrom) was not collected; network columns left blank."
        }
        if (-not $pl.NetworkAccess) { $pl.NetworkAccess = 'N/A' }
        return @{ Placement = $pl; Attachments = $att }
    }
    if ($net.SelfSubnetId) {
        $s = Resolve-SubnetInfo -SubnetId $net.SelfSubnetId -Record $Record
        foreach ($f in @('VNetSubscriptionId', 'VNetResourceGroup', 'VNetName', 'SubnetName', 'SubnetPrefix')) { $pl[$f] = $s[$f] }
        $pl.NetworkAccess = 'N/A'
        $pl.PrivateEndpointCount = $net.SelfPeCount
        return @{ Placement = $pl; Attachments = $att }
    }
    if ($net.SelfVNetId) {
        $v = $script:State.VNets[(ConvertTo-Lower $net.SelfVNetId)]
        if ($v) { $pl.VNetSubscriptionId = $v.SubscriptionId; $pl.VNetResourceGroup = $v.ResourceGroup; $pl.VNetName = $v.Name }
        $pl.NetworkAccess = 'N/A'
        $pl.PrivateEndpointCount = $net.SelfPeCount
        return @{ Placement = $pl; Attachments = $att }
    }

    foreach ($ref in $net.NicRefs) {
        $nic = $script:State.Nics[(ConvertTo-Lower $ref.Id)]
        if (-not $nic) {
            Add-ErrorRow -SubscriptionId $Record.SubscriptionId -Module $Record.Module -ResourceKey $Record.ResourceId -Operation 'ResolveNic' `
                -Message "NIC $($ref.Id) was not found in the collected network backbone; network columns left blank."
            continue
        }
        $s = Resolve-SubnetInfo -SubnetId $nic.SubnetId -Record $Record
        $att.Add((New-AttachmentRow -ResourceKey $key -Type 'Nic' -IsPrimary $ref.Primary -SubnetInfo $s -PrivateIp $nic.PrivateIp -PeName '' -GroupId ''))
    }
    if ($net.DelegatedSubnetId) {
        $s = Resolve-SubnetInfo -SubnetId $net.DelegatedSubnetId -Record $Record
        $att.Add((New-AttachmentRow -ResourceKey $key -Type 'DelegatedSubnet' -IsPrimary $true -SubnetInfo $s -PrivateIp '' -PeName '' -GroupId ''))
    }
    $first = $true
    foreach ($sid in $net.NodePoolSubnets) {
        $s = Resolve-SubnetInfo -SubnetId $sid -Record $Record
        $att.Add((New-AttachmentRow -ResourceKey $key -Type 'NodePool' -IsPrimary $first -SubnetInfo $s -PrivateIp '' -PeName '' -GroupId ''))
        $first = $false
    }
    $peCount = 0
    if ($net.PeTargetId) {
        $list = $script:State.PeByTarget[(ConvertTo-Lower $net.PeTargetId)]
        if ($list) {
            foreach ($pe in $list) {
                $groups = @($pe.GroupIds)
                if ($net.PeGroupFilter) {
                    $match = $false
                    foreach ($g in $groups) { if ($net.PeGroupFilter -contains [string]$g) { $match = $true } }
                    if (-not $match) { continue }
                }
                $peCount++
                $s = Resolve-SubnetInfo -SubnetId $pe.SubnetId -Record $Record
                $att.Add((New-AttachmentRow -ResourceKey $key -Type 'PrivateEndpoint' -IsPrimary $false -SubnetInfo $s -PrivateIp $pe.PrivateIp -PeName $pe.Name -GroupId (Join-List $groups)))
            }
        }
    }
    foreach ($sid in $net.VNetRuleSubnetIds) {
        $s = Resolve-SubnetInfo -SubnetId $sid -Record $Record
        $att.Add((New-AttachmentRow -ResourceKey $key -Type 'VNetRule' -IsPrimary $false -SubnetInfo $s -PrivateIp '' -PeName '' -GroupId ''))
    }

    # Primary attachment: primary NIC / delegated subnet / first node pool, else first private
    # endpoint, else first vNet rule.
    $primary = $null
    foreach ($a in $att) { if ($a.IsPrimary) { $primary = $a; break } }
    if (-not $primary) { foreach ($a in $att) { if ($a.AttachmentType -eq 'PrivateEndpoint') { $primary = $a; break } } }
    if (-not $primary) { foreach ($a in $att) { if ($a.AttachmentType -eq 'VNetRule') { $primary = $a; break } } }
    if (-not $primary -and $att.Count -gt 0) { $primary = $att[0] }
    foreach ($a in $att) { $a.IsPrimary = [object]::ReferenceEquals($a, $primary) }
    if ($primary) {
        foreach ($f in @('VNetSubscriptionId', 'VNetResourceGroup', 'VNetName', 'SubnetName', 'SubnetPrefix')) { $pl[$f] = $primary[$f] }
    }
    $pl.PrivateEndpointCount = $peCount
    if ($net.ExplicitAccess) { $pl.NetworkAccess = $net.ExplicitAccess }
    elseif ($net.PeTargetId -and $peCount -eq 0 -and -not $net.VNetInjected -and $net.HasSurface -and $script:State.PeListingFailed.Count -gt 0) {
        # Private endpoint listing failed somewhere: an endpoint may exist that we could not see, so do
        # not report a confident (and possibly wrong) access mode or a zero count.
        $pl.NetworkAccess = 'Unknown'
        $pl.PrivateEndpointCount = ''
    }
    else {
        $pl.NetworkAccess = Resolve-NetworkAccess -HasNetworkSurface $net.HasSurface -VNetInjected $net.VNetInjected -PrivateEndpointCount $peCount `
            -PublicNetworkAccess $net.PublicNetworkAccess -DefaultAction $net.DefaultAction -VNetRuleCount $net.VNetRuleSubnetIds.Count -IpRuleCount $net.IpRuleCount
    }
    return @{ Placement = $pl; Attachments = $att }
}

